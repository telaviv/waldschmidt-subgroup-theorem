"""Generate LSG/MEV/FibreId{i}{a}.lean from fibre_ids.pkl (run fibre_ids.py first).
Usage (from this folder): python gen_fibre.py OUTDIR"""
import pickle, sys, os
import sympy as sp
from fibre_ids import u, v, s, Q0, Q1, Q2
from defs import g2, g3

SUB = {0: '₁', 1: '₂'}
LM = {0: 'V', 1: 'W'}

def lean(e, a):
    names = {u: 'P0', v: ('P2' if a == 0 else 'P1'), Q0: 'Q0', Q1: 'Q1', Q2: 'Q2', g2: 'G2',
             g3: 'G3', s: 'S'}
    e = sp.expand(e)
    if e == 0:
        return '0'
    txt = sp.sstr(e.subs(names and {k: sp.Symbol(n) for k, n in names.items()},
                         simultaneous=True), order='lex')
    txt = txt.replace('**', '^')
    for k in ['P0', 'P1', 'P2', 'Q0', 'Q1', 'Q2']:
        txt = txt.replace(k, f'({k[0]} {k[1]})')
    return txt.replace('G2', 'g₂').replace('G3', 'g₃').replace('S', 's')

HEAD = '''import Mathlib
import LSG.MEV.FibreDefs

/-!
# Fibre identities for the `E^♮` laws, `law{I}`, moving chart `{A}` (generated)

Generated by `scripts/mev_curve/gen_fibre.py` from the sympy certificates of
`scripts/mev_curve/fibre_ids.py`: `fibE D i j k a b g₂ g₃ s P Q = f₁ F(P) + f₂ F(Q)`
for `D P = s c2_a(P)`, `D Q = 0`, `P_a = 1`.
-/

open LSG.Elliptic LSG.ME

set_option linter.style.longLine false

namespace LSG.MEV

variable {{R : Type*}} [CommRing R]
'''

LEMMA = '''
set_option maxHeartbeats 4000000 in
set_option maxRecDepth 20000 in
theorem fibId_{i}{j}{k}_{a}{b} {{S : Type*}} [CommRing S] [Algebra S R] (D : Derivation S R R)
    (g₂ g₃ s : R) (P Q : Fin 3 → R) (hg₂ : D g₂ = 0) (hg₃ : D g₃ = 0)
    (hQ : ∀ j, D (Q j) = 0) (hP : ∀ j, D (P j) = s * c2 (biE {a}) g₂ g₃ P j)
    (hPa : P (biE {a}) = 1) :
    ∃ f₁ f₂ : R, fibE D {i} {j} {k} {a} {b} g₂ g₃ s P Q = f₁ * Fv g₂ g₃ P + f₂ * Fv g₂ g₃ Q := by
  have h0 := hP 0; have h1 := hP 1; have h2 := hP 2
  have q0 := hQ 0; have q1 := hQ 1; have q2 := hQ 2
  simp only [biE, c2, Fin.isValue, Matrix.cons_val_zero, Matrix.cons_val_one, Matrix.cons_val_two,
    Matrix.head_cons, Matrix.tail_cons] at h0 h1 h2 hPa
  simp only [fibE, biE, rhoh, kapB, epsT, mult, lawSel, law{I}, law{I}U, law{I}V, law{I}W, kapW, kapV,
    kapW{I}{L1}{L2}, kapV{I}{L1}{L2}, Fv, F, Fin.isValue,
    Matrix.cons_val_zero, Matrix.cons_val_one, Matrix.cons_val_two, Matrix.head_cons,
    Matrix.tail_cons, map_add, map_sub, map_neg, map_mul, Derivation.leibniz, Derivation.leibniz_pow,
    smul_eq_mul, nsmul_eq_mul, D_ofNat, h0, h1, h2, q0, q1, q2, hg₂, hg₃, Nat.cast_ofNat,
    mul_zero, add_zero, zero_add, sub_zero, neg_zero, Nat.reduceSub, pow_one]
  simp only [hPa]
  exact ⟨{f1},
    {f2}, by ring⟩
'''

def main():
    out = sys.argv[1]
    res = pickle.load(open('fibre_ids.pkl', 'rb'))
    for i in range(2):
        for a in range(2):
            body = HEAD.format(I=SUB[i], A=LM[a])
            for j in range(2):
                for k in range(2):
                    for b in range(2):
                        q1, q2, ok = res[(i, j, k, a, b)]
                        assert ok
                        body += LEMMA.format(i=i, j=j, k=k, a=a, b=b, I=SUB[i], L1=LM[j], L2=LM[k],
                                             f1=lean(q1, a), f2=lean(q2, a))
            body += '\nend LSG.MEV\n'
            open(os.path.join(out, f'FibreId{i}{a}.lean'), 'w', encoding='utf-8').write(body)

if __name__ == '__main__':
    main()
