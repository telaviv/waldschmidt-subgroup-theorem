"""M2 / B6 for the vector extension (UNTRUSTED generator; Lean re-checks).

With sub: X4 -> -X0 - X8 and G8 = sub(gensMv) ++ sub(wq), wq = (2X1² − X0X3, X2X5 − X1X6, −8X1X2 + X5X7 − 2X3X8)
(the T = 0 parts of P04, P08, 4·P48):   D_v X_v^5 = Σ_k c_k G8_k   for the 8 variables v ≠ 4 (degree 5).
Writes LSG/Jac/Data/B6V.lean, LSG/Jac/Cert/B6V_<v>.lean.  Usage (from lean_lsg/): python scripts/jac/gen_jac_b6v.py
"""
import os, sys
from math import lcm
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'm2_spike'))
import m2_common  # noqa: F401  (sets sys.path)
import jb_common as jb
from m2_b6lin import WQ, member8
ROOT = os.path.join(HERE, '..', '..', 'LSG', 'Jac')
HDR = ['/-', 'Copyright (c) 2026. All rights reserved.', 'Released under Apache 2.0 license.', '-/']
X = jb.X
VARS8 = [0, 1, 2, 3, 5, 6, 7, 8]

def code(e): return sum(e[i] * 8 ** i for i in range(9))

def intpoly(p):
    out = {}
    for e, c in p.to_dict().items():
        assert c.q == 1, p
        out[code(e)] = int(c.p)
    return out

def row_lit(d):
    return '[' + ', '.join(f'({c}, {abs(v)}, {"true" if v < 0 else "false"})' for c, v in sorted(d.items()) if v) + ']'

def sp_lit(d):
    return '⟨[' + ', '.join(f'({c}, [(0, {abs(v)}, {"true" if v < 0 else "false"})])' for c, v in sorted(d.items()) if v) + \
        '], [0]⟩'

def sub(p):
    return p.compose(*[X[i] if i != 4 else -X[0] - X[8] for i in range(9)])

def main():
    wq = [WQ[0], WQ[1], 4 * WQ[2]]
    G = jb.GENS + wq
    G8 = [sub(g) for g in G]
    L = HDR + ['import LSG.Jac.B56Check', '', '/-! GENERATED by scripts/jac/gen_jac_b6v.py — do not edit.', '',
               'B6 for `A^♮` (M2.1.3): `wqRows` (the `T = 0` parts of `P04`, `P08`, `4·P48`), `subRows` (the 15 generators',
               'after `X₄ ↦ −X₀ − X₈`), and the identities `D_v X_v⁵ = Σ_k c_k sub(G_k)`. -/', '',
               'namespace LSG.Jac.Data', '', 'open LSG.Jac', '',
               'def wqRows : List (List (Nat × Nat × Bool)) := [' + ', '.join(row_lit(intpoly(w)) for w in wq) + ']', '',
               'def subRows : List (List (Nat × Nat × Bool)) := [' + ', '.join(row_lit(intpoly(g)) for g in G8) + ']', '',
               'def subSP (k : Nat) : SP := rowSP (subRows.getD k [])', '']
    tot = 0
    for v in VARS8:
        cof = member8(X[v] ** 5, G8)
        assert cof is not None
        D = 1
        for c in cof:
            for x in c.to_dict().values():
                D = lcm(D, int(x.q))
        parts = []
        for k, c in enumerate(cof):
            if c != 0:
                L.append(f'noncomputable def b6v_{v}_c{k} : SP := {sp_lit(intpoly(c * D))}')
                parts.append(f'(b6v_{v}_c{k}, subSP {k})')
                tot += len(c.to_dict())
        L.append(f'noncomputable def b6v_{v} : List Term := idTerms {D} (monoSP (5 * 8 ^ {v})) oneSP [' + ', '.join(parts) + ']')
        L.append('')
        print(v, 'D', D, 'terms', sum(len(c.to_dict()) for c in cof), flush=True)
    L += ['end LSG.Jac.Data']
    open(os.path.join(ROOT, 'Data', 'B6V.lean'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    for v in VARS8:
        nm = f'b6v_{v}'
        Lc = HDR + ['import LSG.Jac.Data.B6V', 'import LSG.Jac.Data.B5Id5', '',
                    f'/-! GENERATED by scripts/jac/gen_jac_b6v.py — B6 (`A^♮`) identity for `X_{v}⁵`. -/', '',
                    'namespace LSG.Jac.Cert', '', 'open LSG.Jac LSG.Jac.Data', '', 'set_option maxRecDepth 100000', '',
                    f'theorem {nm}_O : (evalOd 11 idTree5b T0 {nm}).allZero = true := by decide +kernel',
                    f'theorem {nm}_B : wsum {nm} * (1 * 1) < 2 ^ 128 := by decide +kernel',
                    f'theorem {nm}_T : {nm}.all (fun q => termOK2 idTree5b T0 q && q.a.wf && q.b.wf) = true := by decide +kernel',
                    '', 'end LSG.Jac.Cert']
        open(os.path.join(ROOT, 'Cert', f'B6V_{v}.lean'), 'w', encoding='utf-8').write('\n'.join(Lc) + '\n')
    print('total cofactor terms', tot)

if __name__ == '__main__':
    main()
