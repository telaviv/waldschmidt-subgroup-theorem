"""Stage A1: data and raw certificates for the equivariance identities E1/E2 (UNTRUSTED generator).

Writes (LSG/Jac/):
  Data/Table5.lean, Data/NFCert5_<k>.lean   degree-5 normal-form table (X- or Y-side), Y-packing width kb5
  Data/Table4b.lean                         degree-4 table, same rows as Data/Table.lean, Y-packing width kb4b
  Data/IdTab.lean                           identity tables of degrees 2 and 3 (exact checks)
  Data/E1.lean                              flow quadratics as SPs, merged derivatives DA
  Cert/T5_<k>.lean, Cert/T5base.lean        table checks
  Cert/DA_<fam>.lean                        exact checks  DA = sum_i W_in,ji * dA/dS_i
  Cert/E1_<fam>_<j>.lean                    main checks, split by X-slot ranges
Usage (from lean_lsg/):  python scripts/jac/gen_jac_e1.py [--only-tables]
"""
import itertools, json, os, sys
import flint
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import slots
from lift5 import LifterD, load_quads
from e1_data import FAMILIES, DA, Wn, W4n, law_terms, dig
ROOT = os.path.join(HERE, '..', '..', 'LSG', 'Jac')
D5 = 691200
KB = 92          # Y-packing width for Table4b and Table5
KBID = 64        # identity tables
NSLOT5, NSLOT4 = 225, 144
RANGES5 = int(os.environ.get('E1_RANGES5', '5'))
RANGES5_L4 = int(os.environ.get('E1_RANGES5_L4', '9'))
RANGES4_L4 = int(os.environ.get('E1_RANGES4_L4', '6'))

def code(m): return sum(8 ** i for i in m)
def ent(c, v): return f'({c}, {abs(v)}, {"true" if v < 0 else "false"})'
def nat_pair(row, width):
    pp = [f'({v} <<< {width * t})' for t, v in row if v > 0]
    nn = [f'({-v} <<< {width * t})' for t, v in row if v < 0]
    return '(' + (' + '.join(pp) or '0') + ', ' + (' + '.join(nn) or '0') + ')'
HDR_DATA = ['import LSG.Jac.Checker', '']
def write(path, lines):
    with open(os.path.join(ROOT, path), 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(lines) + '\n')

def table5():
    quads = load_quads()
    L = LifterD(quads, 5)
    rows, certs = {}, {}
    for c, mono in enumerate(L.monos):
        nf, cof = L.lift({c: flint.fmpq(1)})
        rows[mono] = {col: int((v * D5).p) for col, v in nf.items()}
        for v in nf.values():
            assert (v * D5).q == 1
        cj = [dict() for _ in range(9)]
        for (m3, i), v in cof.items():
            w = v * D5
            assert w.q == 1
            cj[i][code(m3)] = int(w.p)
        certs[mono] = cj
    stdcols = sorted({col for r in rows.values() for col in r})
    assert len(stdcols) == NSLOT5
    tpos = {col: t for t, col in enumerate(stdcols)}
    stdc = [code(L.monos[col]) for col in stdcols]
    keyed = sorted(L.monos, key=code)
    keys = [code(m) for m in keyed]
    M = max(sum(abs(v) for v in rows[m].values()) for m in L.monos)
    out = HDR_DATA + ['/-! GENERATED by scripts/jac/gen_jac_e1.py — do not edit. Degree-5 normal-form table modulo the',
                      f'quadrics, rows scaled by `nfDelta5 = {D5}`, `Y`-packing width `kb5`. -/', '',
                      'namespace LSG.Jac.Data', '', 'open LSG.Jac', '',
                      f'def kb5 : Nat := {KB}', f'def rowM5 : Nat := {M}', f'def nfDelta5 : Nat := {D5}', '',
                      'def stdc5 : List Nat := [' + ', '.join(map(str, stdc)) + ']', '',
                      'def keys5 : List Nat := [' + ', '.join(map(str, keys)) + ']', '']
    for idx, m in enumerate(keyed):
        row = sorted((tpos[col], v) for col, v in rows[m].items())
        out.append(f'noncomputable def l5_{idx} : Leaf := ⟨{code(m)}, {idx}, [' + ', '.join(ent(t, v) for t, v in row) +
                   f'],\n  {nat_pair(row, KB)}⟩')
    def tree(lo, hi):
        if hi - lo == 1:
            return f'(.leaf l5_{lo})'
        mid = (lo + hi) // 2
        return f'(.node {keys[mid]} {tree(lo, mid)} {tree(mid, hi)})'
    out += ['', 'noncomputable def nfTree5 : T := ' + tree(0, len(keyed)), '', 'end LSG.Jac.Data']
    write('Data/Table5.lean', out)
    # certificate chunks, by total cofactor products
    qlen = [len(q) for q in quads]
    chunks, cur, curw = [], [], 0
    maxw = 0
    for m in keyed:
        w = sum(len(certs[m][i]) * qlen[i] for i in range(9))
        tw = D5 + sum(abs(v) for v in rows[m].values()) + sum(abs(c) * abs(qc) for i in range(9)
                                                                 for c in certs[m][i].values() for qc in quads[i].values())
        maxw = max(maxw, tw)
        if cur and curw + w > int(os.environ.get("NF5_CHUNK", "11000")):
            chunks.append(cur); cur, curw = [], 0
        cur.append(m); curw += w
    chunks.append(cur)
    B5 = maxw.bit_length() + 1
    offs, a = [], 0
    for k, ch in enumerate(chunks):
        offs.append(a)
        lines = HDR_DATA + [f'/-! GENERATED by scripts/jac/gen_jac_e1.py — degree-5 normal-form certificates, chunk {k}. -/', '',
                            'namespace LSG.Jac.Data', '']
        names = []
        for m in ch:
            parts = ['[' + ', '.join(ent(c, v) for c, v in sorted(certs[m][i].items())) + ']' for i in range(9)]
            lines.append(f'noncomputable def nc5_{a} : Nat × List (List (Nat × Nat × Bool)) := ({code(m)}, [{", ".join(parts)}])')
            names.append(f'nc5_{a}'); a += 1
        lines += ['', f'noncomputable def nfc5_{k} : List (Nat × List (List (Nat × Nat × Bool))) := [' + ', '.join(names) + ']',
                  '', 'end LSG.Jac.Data']
        write(f'Data/NFCert5_{k}.lean', lines)
        cl = ['import LSG.Jac.Data.Table5', 'import LSG.Jac.Data.Table', f'import LSG.Jac.Data.NFCert5_{k}',
              'import LSG.Jac.CheckerNF2', '', f'/-! GENERATED — degree-5 table check, leaves {offs[k]} … {a - 1}. -/', '',
              'namespace LSG.Jac.Cert', '', 'open LSG.Jac LSG.Jac.Data', '', 'set_option maxRecDepth 100000', '',
              f'theorem nf5_ok_{k} : nfRangeOK nfTree5 {B5} 1287 nfDelta5 stdc5 Qd {offs[k]} nfc5_{k} = true := by decide +kernel',
              '', 'end LSG.Jac.Cert']
        write(f'Cert/T5_{k}.lean', cl)
    print(f'Table5: M5 = {M}, {len(chunks)} certificate chunks, B5 = {B5}')
    return len(chunks), offs, [len(c) for c in chunks], B5, M

def table4b():
    tab = open(os.path.join(ROOT, 'Data', 'Table.lean'), encoding='utf-8').read()
    import re
    kb4 = int(re.search(r'def kb : Nat := (\d+)', tab).group(1))
    out = HDR_DATA + ['/-! GENERATED by scripts/jac/gen_jac_e1.py — the degree-4 table of `Data/Table.lean` with `Y`-packing',
                      'width `kb4b` (same keys and rows, checked by `sameRows`). -/', '', 'namespace LSG.Jac.Data', '',
                      'open LSG.Jac', '', f'def kb4b : Nat := {KB}', '']
    keys = []
    for mm in re.finditer(r'noncomputable def lf(\d+) : Leaf := ⟨(\d+), (\d+), \[(.*?)\],', tab):
        idx, key, row = int(mm.group(1)), int(mm.group(2)), slots.trip(mm.group(4))
        keys.append(key)
        rr = [(t, -v if s else v) for t, v, s in row]
        out.append(f'noncomputable def l4b_{idx} : Leaf := ⟨{key}, {idx}, [{mm.group(4)}],\n  {nat_pair(rr, KB)}⟩')
    def tree(lo, hi):
        if hi - lo == 1:
            return f'(.leaf l4b_{lo})'
        mid = (lo + hi) // 2
        return f'(.node {keys[mid]} {tree(lo, mid)} {tree(mid, hi)})'
    out += ['', 'noncomputable def nfTree4b : T := ' + tree(0, len(keys)), '', 'end LSG.Jac.Data']
    write('Data/Table4b.lean', out)

def idtabs():
    out = HDR_DATA + ['/-! GENERATED by scripts/jac/gen_jac_e1.py — identity tables of degrees 2 and 3 (`δ = 1`). -/', '',
                      'namespace LSG.Jac.Data', '', 'open LSG.Jac', '', f'def kbId : Nat := {KBID}', '']
    for d in (2, 3):
        mons = sorted(itertools.combinations_with_replacement(range(9), d), key=code)
        keys = [code(m) for m in mons]
        out.append(f'def stdcId{d} : List Nat := [' + ', '.join(map(str, keys)) + ']')
        for i, k in enumerate(keys):
            out.append(f'noncomputable def id{d}_{i} : Leaf := ⟨{k}, {i}, [({i}, 1, false)], (1 <<< {KBID * i}, 0)⟩')
        def tree(lo, hi):
            if hi - lo == 1:
                return f'(.leaf id{d}_{lo})'
            mid = (lo + hi) // 2
            return f'(.node {keys[mid]} {tree(lo, mid)} {tree(mid, hi)})'
        out += [f'noncomputable def idTree{d} : T := ' + tree(0, len(keys)), '']
    out.append('end LSG.Jac.Data')
    write('Data/IdTab.lean', out)

DAFAMS = {  # name: (m, side, Win, letter)
    'X0W4': (0, 'X', W4n), 'X0W': (0, 'X', Wn), 'X4W4': (4, 'X', W4n), 'Y4W4': (4, 'Y', W4n)}
FAM_DA = {'E40': 'X0W4', 'E44': 'X0W4', 'E04': 'X0W', 'F4X': 'X4W4', 'F4Y': 'Y4W4'}

def wsp(Win, j, i, side):
    w = Win.get((j, i), {})
    if side == 'X':
        rows = [f'({c}, [(0, {abs(v)}, {"true" if v < 0 else "false"})])' for c, v in sorted(w.items())]
        return f'⟨[{", ".join(rows)}], [0]⟩'
    ents = ', '.join(ent(c, v) for c, v in sorted(w.items()))
    return f'⟨[(0, [{ents}])], {sorted(w)}⟩'

def sp_lit(poly):
    rows = {}
    for (a, b), v in sorted(poly.items()):
        rows.setdefault(a, []).append((b, v))
    rs = [f'({a}, [' + ', '.join(ent(b, v) for b, v in r) + '])' for a, r in sorted(rows.items())]
    yc = sorted({b for (a, b) in poly})
    return f'⟨[{", ".join(rs)}],\n  {yc}⟩'

def e1_data():
    laws = slots.load_laws()
    out = HDR_DATA + ['/-! GENERATED by scripts/jac/gen_jac_e1.py — E1 data: flow quadratics as SPs (`WX0 = 2W`, `WX4 = 4W⁽⁴⁾`',
                      'on the `X`-side, `WY4` on the `Y`-side) and merged derivatives `DA_<fam>_j_l = Σ_i W_in,ji ∂A_l/∂S_i`. -/',
                      '', 'namespace LSG.Jac.Data', '', 'open LSG.Jac', '']
    for nm, Win, side in (('WX0', Wn, 'X'), ('WX4', W4n, 'X'), ('WY4', W4n, 'Y')):
        for j in (0, 1):
            for i in range(9):
                out.append(f'noncomputable def {nm}_{j}_{i} : SP := {wsp(Win, j, i, side)}')
    out.append('')
    for fam, (m, side, Win) in DAFAMS.items():
        for j in (0, 1):
            for l in range(9):
                out.append(f'noncomputable def DA_{fam}_{j}_{l} : SP := {sp_lit(DA(laws, l, m, side, Win, j))}')
    out += ['', 'end LSG.Jac.Data']
    write('Data/E1.lean', out)

def da_certs():
    for fam, (m, side, Win) in DAFAMS.items():
        wnm = {'X0W4': 'WX4', 'X0W': 'WX0', 'X4W4': 'WX4', 'Y4W4': 'WY4'}[fam]
        trX, trY = ('idTree3', 'idTree2') if side == 'X' else ('idTree2', 'idTree3')
        d = 'dXsp' if side == 'X' else 'dYsp'
        L = ['import LSG.Jac.Data.Laws', 'import LSG.Jac.Data.IdTab', 'import LSG.Jac.Data.E1', 'import LSG.Jac.CheckerDeriv',
             'import LSG.Jac.CheckerDiag', '', f'/-! GENERATED — exact checks `DA_{fam}_j_l = Σ_i {wnm}_j_i · {d} i (law l {m})`. -/', '',
             'namespace LSG.Jac.Cert', '', 'open LSG.Jac LSG.Jac.Data', '', 'set_option maxRecDepth 100000', '']
        for j in (0, 1):
            for l in range(9):
                n = f'da_{fam}_{j}_{l}'
                terms = [f'⟨1, false, {wnm}_{j}_{i}, {d} {i} (law {l} {m})⟩' for i in range(9) if Win.get((j, i))]
                terms.append(f'⟨1, true, DA_{fam}_{j}_{l}, oneSP⟩')
                L += [f'noncomputable def {n} : List Term := [' + ', '.join(terms) + ']',
                      f'theorem {n}_O : (evalO2 {trX} {trY} {n}).allZero = true := by decide +kernel',
                      f'theorem {n}_B : wsum {n} * (1 * 1) < 2 ^ kbId := by decide +kernel',
                      f'theorem {n}_T : {n}.all (fun q => termOK2 {trX} {trY} q && q.a.wf && q.b.wf) = true := by decide +kernel', '']
        L.append('end LSG.Jac.Cert')
        write(f'Cert/DA_{fam}.lean', L)

BUDGET_X = int(os.environ.get('E1_BUDGET_X', '50000'))   # e1_cost units (≈ 3.0 GB per declaration, STAGE_A1 §10)
BUDGET_Y = int(os.environ.get('E1_BUDGET_Y', '42000'))

def e1_certs(M5=None, M4=3502080):
    from e1_cost import ranges_for
    laws = slots.load_laws()
    for fam, (m, side, Win, sin, c, Wout, sout, f) in FAMILIES.items():
        da = FAM_DA[fam]
        if side == 'X':
            trX, trY, shift, budget = 'nfTree5', 'nfTree4b', 'shiftX', BUDGET_X
            bnd = f'wsum ps * (rowM5 * rowM) < 2 ^ kb4b'
        else:
            trX, trY, shift, budget = 'nfTree', 'nfTree5', 'shiftY', BUDGET_Y
            bnd = f'wsum ps * (rowM * rowM5) < 2 ^ kb5'
        for j in (0, 1):
            L = ['import LSG.Jac.Data.Laws', 'import LSG.Jac.Data.Table', 'import LSG.Jac.Data.Table4b',
                 'import LSG.Jac.Data.Table5', 'import LSG.Jac.Data.E1', 'import LSG.Jac.CheckerRange', '',
                 f'/-! GENERATED — equivariance identities `{fam}` (law {m}, `{side}`-flow, output chart {c}), j = {j}, split by',
                 f'`X`-slot ranges `rs_e1_{fam}_{j}_<l>` (adaptive, `scripts/jac/e1_cost.py`, budget {budget}). -/', '',
                 'namespace LSG.Jac.Cert', '', 'open LSG.Jac LSG.Jac.Data', '', 'set_option maxRecDepth 100000', '']
            for l in range(9):
                if l == c:
                    continue
                n = f'e1_{fam}_{j}_{l}'
                rs, _ = ranges_for(fam, j, l, budget)
                terms = [f'⟨{sout}, false, law {c} {m}, DA_{da}_{j}_{l}⟩', f'⟨{sout}, true, law {l} {m}, DA_{da}_{j}_{c}⟩']
                for cd, coef in sorted(Wout.get((j, l), {}).items()):
                    ab = [i for i in range(9) for _ in range(dig(cd, i))]
                    w = -sin * coef
                    terms.append(f'⟨{abs(w)}, {"true" if w < 0 else "false"}, {shift} {f} (law {ab[0]} {m}), law {ab[1]} {m}⟩')
                L += [f'def rs_{n} : List (Nat × Nat) := [' + ', '.join(f'({a}, {b})' for a, b in rs) + ']',
                      f'noncomputable def {n} : List Term := [' + ', '.join(terms) + ']']
                for k, (a, b) in enumerate(rs):
                    L.append(f'theorem {n}_R{k} : (evalO2 ({trX}.mapRows (rowsIn {a} {b})) {trY} {n}).allZero = true := by decide +kernel')
                L += [f'theorem {n}_B : ' + bnd.replace('ps', n) + ' := by decide +kernel',
                      f'theorem {n}_T : {n}.all (fun q => termOK2 {trX} {trY} q && q.a.wf && q.b.wf) = true := by decide +kernel',
                      '']
            L.append('end LSG.Jac.Cert')
            write(f'Cert/E1_{fam}_{j}.lean', L)

