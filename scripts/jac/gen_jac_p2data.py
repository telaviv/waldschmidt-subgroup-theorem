"""Stage A1, P2: Lean data and certificate files from p2_cert.json (UNTRUSTED generator; Lean re-checks everything).

Writes LSG/Jac/Data/P2Tab.lean (degree-7 identity table, 6435 leaves), LSG/Jac/Data/P2.lean (cofactors),
LSG/Jac/Cert/P2base.lean and LSG/Jac/Cert/P2_<i>.lean (one kernel check per i).
Usage (from lean_lsg/): python scripts/jac/gen_jac_p2data.py
"""
import itertools, json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import slots
ROOT = os.path.join(HERE, '..', '..', 'LSG', 'Jac')
HDR = ['/-', 'Copyright (c) 2026. All rights reserved.', 'Released under Apache 2.0 license.', '-/']
DEPTH = 13

def code(m): return sum(8 ** i for i in m)

def write(path, lines):
    open(path, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')

def sp_lit(poly):
    """poly: dict code -> int (single copy)."""
    rows = [f'({c}, [(0, {abs(v)}, {"true" if v < 0 else "false"})])' for c, v in sorted(poly.items()) if v]
    return '⟨[' + ', '.join(rows) + '], [0]⟩'

def main():
    cert = json.load(open(os.path.join(HERE, 'p2_cert.json')))
    keys = sorted(code(m) for m in itertools.combinations_with_replacement(range(9), 7))
    assert len(keys) == 6435 and len(keys) <= 2 ** DEPTH
    # identity table
    L = HDR + ['import LSG.Jac.Checker', '', '/-! GENERATED by scripts/jac/gen_jac_p2data.py — do not edit.', '',
               'The degree-7 identity table (`δ = 1`, 6435 slots) for P2. -/', '', 'namespace LSG.Jac.Data', '',
               'open LSG.Jac', '']
    for i, k in enumerate(keys):
        L.append(f'noncomputable def p7_{i} : Leaf := ⟨{k}, {i}, [({i}, 1, false)], (0, 0)⟩')
    def tree(lo, hi):
        if hi - lo == 1:
            return f'(.leaf p7_{lo})'
        mid = (lo + hi) // 2
        return f'(.node {keys[mid]} {tree(lo, mid)} {tree(mid, hi)})'
    L += ['', 'noncomputable def idTree7 : T := ' + tree(0, len(keys)), '',
          '/-- The standard monomials of `idTree7` (= its keys, in order). -/',
          'noncomputable def stdc7 : List Nat := idTree7.leaves.map Leaf.key', '', 'end LSG.Jac.Data']
    write(os.path.join(ROOT, 'Data', 'P2Tab.lean'), L)
    # cofactors
    L = HDR + ['import LSG.Jac.CheckerP2', '', '/-! GENERATED by scripts/jac/gen_jac_p2data.py — do not edit.', '',
               'P2 cofactors: `D_i X_i⁷ = Σ_k C_ik dup_k + Σ_j H_ij Q_j` (`scripts/jac/gen_jac_p2.py`). -/', '',
               'namespace LSG.Jac.Data', '', 'open LSG.Jac', '']
    laws = slots.load_laws()
    ndiag = []
    for k in range(9):
        n = sum(len(r) for a, r in laws[(k, 4)])
        ndiag.append(n)
    qd = slots.load_quads() if hasattr(slots, 'load_quads') else None
    for i in range(9):
        si = str(i)
        C = [dict() for _ in range(9)]
        for k, m, v in cert['C'][si]:
            c = code(m); C[k][c] = C[k].get(c, 0) + int(v)
        H = [dict() for _ in range(9)]
        for j, m, v in cert['H'][si]:
            c = code(m); H[j][c] = H[j].get(c, 0) + int(v)
        L.append(f'def p2D_{i} : Nat := {cert["D"][si]}')
        for k in range(9):
            L.append(f'noncomputable def p2C_{i}_{k} : SP := {sp_lit(C[k])}')
        for j in range(9):
            L.append(f'noncomputable def p2H_{i}_{j} : SP := {sp_lit(H[j])}')
        L.append(f'noncomputable def p2ps_{i} : List Term := p2Terms p2D_{i} {i} [' +
                 ', '.join(f'p2C_{i}_{k}' for k in range(9)) + '] [' + ', '.join(f'p2H_{i}_{j}' for j in range(9)) + ']')
        L.append('')
        prods = sum(len(C[k]) * ndiag[k] for k in range(9)) + sum(len(H[j]) * 3 for j in range(9))
        print(f'i={i}: ~{prods} products')
    L += ['end LSG.Jac.Data']
    write(os.path.join(ROOT, 'Data', 'P2.lean'), L)
    # certificates
    base = HDR + ['import LSG.Jac.Data.P2Tab', 'import LSG.Jac.CheckerP2', '',
                  '/-! GENERATED by scripts/jac/gen_jac_p2data.py — structural checks for P2. -/', '',
                  'namespace LSG.Jac.Cert', '', 'open LSG.Jac LSG.Jac.Data', '',
                  'theorem p7_seq : idSeqOK idTree7.leaves 0 = true := by decide +kernel',
                  'theorem p7_len : idTree7.leaves.length = 6435 := by decide +kernel',
                  'theorem dup_diagOK : (List.range 9).all (fun k => diagOK (law k 4)) = true := by decide +kernel', '',
                  'end LSG.Jac.Cert']
    write(os.path.join(ROOT, 'Cert', 'P2base.lean'), base)
    for i in range(9):
        L = HDR + ['import LSG.Jac.Data.P2Tab', 'import LSG.Jac.Data.P2', '',
                   f'/-! GENERATED by scripts/jac/gen_jac_p2data.py — the P2 identity for `X_{i}` (exact). -/', '',
                   'namespace LSG.Jac.Cert', '', 'open LSG.Jac LSG.Jac.Data', '', 'set_option maxRecDepth 100000', '',
                   f'theorem p2_O_{i} : (evalOd {DEPTH} idTree7 T0 p2ps_{i}).allZero = true := by decide +kernel',
                   f'theorem p2_B_{i} : wsum p2ps_{i} * (1 * 1) < 2 ^ 128 := by decide +kernel',
                   f'theorem p2_T_{i} : p2ps_{i}.all (fun q => termOK2 idTree7 T0 q && q.a.wf && q.b.wf) = true := by',
                   '  decide +kernel', '', 'end LSG.Jac.Cert']
        write(os.path.join(ROOT, 'Cert', f'P2_{i}.lean'), L)
    print('wrote P2Tab, P2, P2base, P2_0..8')

if __name__ == '__main__':
    main()
