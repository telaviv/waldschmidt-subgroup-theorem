FV = ', '.join(f'fin9_val_{k}' for k in range(9))

def dafun(fam):
    lines = [f'/-- The merged derivatives `DA_{fam}` as a function of `(j, l)`. -/',
             f'noncomputable def DA{fam} : ℕ → ℕ → SP']
    for j in (0, 1):
        for l in range(9):
            lines.append(f'  | {j}, {l} => DA_{fam}_{j}_{l}')
    lines += ['  | _, _ => ⟨[], []⟩', '']
    return lines

def da_all(fam, fn, side, m):
    v = 'X' if side == 'X' else 'Y'
    d = 'dXsp' if side == 'X' else 'dYsp'
    lines = [f'lemma DA{fam}_eval (X Y : P9) (j : Fin 2) (l : Fin 9) :',
             f'    evalSP X Y (DA{fam} j l) = ∑ i : Fin 9, {fn} {v} j i * evalSP X Y ({d} i (law l {m})) := by',
             '  fin_cases j <;> fin_cases l']
    for j in (0, 1):
        for l in range(9):
            lines.append(f'  · exact da_{fam}_{j}_{l}_eval X Y')
    return lines + ['']

def main_lemma(name, fam, da, m, c, fout, f, sin, sout, side):
    v = 'X' if side == 'X' else 'Y'
    lines = [f'lemma {name}_main (X Y : P9) (hX : OnQ X) (hY : OnQ Y) (j : Fin 2) (l : Fin 9) :',
             f'    ({sout} : ℂ) * (evalSP X Y (law {c} {m}) * evalSP X Y (DA{da} j l) -',
             f'      evalSP X Y (law l {m}) * evalSP X Y (DA{da} j {c})) =',
             f'      {sin} * {v} {f} * {fout} (fun k : Fin 9 => evalSP X Y (law k {m})) j l := by',
             '  fin_cases j <;> fin_cases l']
    for j in (0, 1):
        for l in range(9):
            if l == c:
                lines.append(f'  · simp [{fout}]')
            else:
                lines += [f'  · have h := e1_{fam}_{j}_{l} X Y hX hY',
                          f'    simp only [DA{da}, {FV}] at h ⊢',
                          '    linear_combination h']
    return lines + ['']

