"""Stage A1: generate the flow-invariance (F1) certificates (UNTRUSTED generator; Lean re-checks everything).

F1 (j = 0, 1 <-> d/dz_0, d/dz_1; l = 0..8), on V(Q) x V(Q):
    B * ( Y0 * sum_i Wn_j,i(X) dA_l/dX_i  -  X0 * sum_i Wn_j,i(Y) dA_l/dY_i )  =  3 * GB_j * A_l,
A_l = 32 A_l^(0) (data `law l 0`), Wn = 2 W (integer quadratics, scripts/jac/flow_W.json), B = X1Y0 - X0Y1 + X2Y3 - X3Y2,
GB_j = Y0 sum_i Wn_j,i(X) dB/dX_i - X0 sum_i Wn_j,i(Y) dB/dY_i.  The derivatives dA/dX_i are computed by the kernel
(`dXsp`, `dYsp`); the small factors B*Y0*Wn(X), B*X0*Wn(Y), GB are data (Data/Flow.lean) with evaluation lemmas proved
in LSG/Jac/Flow.lean.

Writes LSG/Jac/Data/Flow.lean, LSG/Jac/Cert/F1j0.lean, LSG/Jac/Cert/F1j1.lean, LSG/Jac/Flow.lean.
Also checks the identities numerically mod p first.
Usage (from lean_lsg/):  python scripts/jac/gen_jac_flow.py
"""
import json
import os
import random
import sys
from fractions import Fraction

import sympy as sp

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', '..')
sys.path.insert(0, HERE)

X = sp.symbols('X0:9')
Y = sp.symbols('Y0:9')
W = {tuple(map(int, k.split(','))): {tuple(m): sp.Rational(c) for m, c in v}
     for k, v in json.load(open(os.path.join(HERE, 'flow_W.json'))).items()}


def Wn(j, i, V):            # j in {0,1} <-> flow_W index 1,2 ; doubled
    return sum(2 * c * V[a] * V[b] for (a, b), c in W.get((j + 1, i), {}).items())


B = X[1] * Y[0] - X[0] * Y[1] + X[2] * Y[3] - X[3] * Y[2]


def GB(j):
    return sp.expand(Y[0] * sum(Wn(j, i, X) * sp.diff(B, X[i]) for i in range(1, 9)) -
                     X[0] * sum(Wn(j, i, Y) * sp.diff(B, Y[i]) for i in range(1, 9)))


def code(e):
    return sum(e[i] * 8 ** i for i in range(9))


def to_sp(expr):
    """sympy poly in X, Y with integer coefficients -> Lean SP literal."""
    P = sp.Poly(sp.expand(expr), *X, *Y)
    rows = {}
    for mon, c in zip(P.monoms(), P.coeffs()):
        assert c == int(c), expr
        rows.setdefault(code(mon[:9]), []).append((code(mon[9:]), int(c)))
    rs = []
    yc = set()
    for a in sorted(rows):
        ents = sorted(rows[a])
        yc |= {b for b, _ in ents}
        rs.append(f'({a}, [' + ', '.join(f'({b}, {abs(c)}, {"true" if c < 0 else "false"})' for b, c in ents) + '])')
    return f'⟨[{", ".join(rs)}], {sorted(yc)}⟩'


def sym_lean(expr, pre='x', pre2='y'):
    s = str(sp.expand(expr))
    for i in range(9):
        s = s.replace(f'X{i}', f'{pre} {i}').replace(f'Y{i}', f'{pre2} {i}')
    return s.replace('**', '^')


def wn_lean(j, i, v):
    e = Wn(j, i, X)
    if e == 0:
        return '0'
    s = str(sp.expand(e))
    for k in range(9):
        s = s.replace(f'X{k}', f'{v} {k}')
    return s.replace('**', '^')


def numeric_check():
    from g1_measure import load_laws, chart_pt, Xof, P
    laws = load_laws()
    A = [sp.expand(sum(c * 32 * sp.prod([X[i] ** ex[i] for i in range(9)]) * sp.prod([Y[i] ** ey[i] for i in range(9)])
                       for ex, ey, c in laws[(l, 0)])) for l in range(9)]
    for j in (0, 1):
        for l in range(9):
            G = Y[0] * sum(Wn(j, i, X) * sp.diff(A[l], X[i]) for i in range(1, 9)) - \
                X[0] * sum(Wn(j, i, Y) * sp.diff(A[l], Y[i]) for i in range(1, 9))
            H = sp.Poly(sp.expand(B * G - 3 * GB(j) * A[l]), *X, *Y)
            for _ in range(2):
                cP, _ = chart_pt()
                cQ, _ = chart_pt()
                v = H.eval(tuple(Xof(cP) + Xof(cQ)))
                assert (int(v.p) * pow(int(v.q), -1, P)) % P == 0, (j, l)
    print('numeric check of F1 (scaled data): OK')


def main():
    numeric_check()
    out = ['import LSG.Jac.Checker', '', '/-! GENERATED by scripts/jac/gen_jac_flow.py — do not edit.', '',
           'Small factors of the flow-invariance identities (F1): `BYW j i = B · Y₀ · Wn_{j,i}(X)`,',
           '`BXW j i = B · X₀ · Wn_{j,i}(Y)`, `GBsp j = Y₀ Σ_i Wn_{j,i}(X) ∂B/∂X_i − X₀ Σ_i Wn_{j,i}(Y) ∂B/∂Y_i`',
           '(`Wn = 2W`, `B = X₁Y₀ − X₀Y₁ + X₂Y₃ − X₃Y₂`). Evaluation lemmas: `LSG.Jac.Flow`. -/', '',
           'namespace LSG.Jac.Data', '', 'open LSG.Jac', '']
    for j in (0, 1):
        for i in range(1, 9):
            out.append(f'noncomputable def BYW{j}{i} : SP := {to_sp(B * Y[0] * Wn(j, i, X))}')
            out.append(f'noncomputable def BXW{j}{i} : SP := {to_sp(B * X[0] * Wn(j, i, Y))}')
        out.append(f'noncomputable def GBsp{j} : SP := {to_sp(GB(j))}')
        out.append('')
    out += ['end LSG.Jac.Data', '']
    open(os.path.join(ROOT, 'LSG', 'Jac', 'Data', 'Flow.lean'), 'w', encoding='utf-8').write('\n'.join(out))
    # ---- raw certificates
    for j in (0, 1):
        L = ['import LSG.Jac.Data.Laws', 'import LSG.Jac.Data.Table', 'import LSG.Jac.Data.Flow',
             'import LSG.Jac.CheckerDeriv', '',
             '/-! GENERATED by scripts/jac/gen_jac_flow.py — do not edit.', '',
             f'Flow invariance (F1) for `∂/∂z_{j}`, `l = 0 … 8`. -/', '',
             'namespace LSG.Jac.Cert', '', 'open LSG.Jac LSG.Jac.Data', '', 'set_option maxRecDepth 100000', '']
        for l in range(9):
            n = f'f1_{j}_{l}'
            terms = []
            for i in range(1, 9):
                terms.append(f'⟨1, false, BYW{j}{i}, dXsp {i} (law {l} 0)⟩')
                terms.append(f'⟨1, true, BXW{j}{i}, dYsp {i} (law {l} 0)⟩')
            terms.append(f'⟨3, true, GBsp{j}, law {l} 0⟩')
            L += [f'/-- `B·G_{{{j}{l}}} − 3·G_B·A_{l}`. -/',
                  f'noncomputable def {n} : List Term :=', '  [' + ',\n   '.join(terms) + ']', '',
                  f'theorem {n}_O : (evalO nfTree {n}).allZero = true := by decide +kernel', '',
                  f'theorem {n}_B : wsum {n} * rowM ^ 2 < 2 ^ kb := by decide +kernel', '',
                  f'theorem {n}_T : {n}.all (fun q => termOK nfTree q && q.a.wf && q.b.wf) = true := by decide +kernel',
                  '']
        L += ['end LSG.Jac.Cert', '']
        open(os.path.join(ROOT, 'LSG', 'Jac', 'Cert', f'F1j{j}.lean'), 'w', encoding='utf-8').write('\n'.join(L))
    # ---- semantic file
    S = ['/-', 'Copyright (c) 2026. All rights reserved.', 'Released under Apache 2.0 license.', '-/',
         'import LSG.Jac.Deriv', 'import LSG.Jac.Cert.F1j0', 'import LSG.Jac.Cert.F1j1', '',
         '/-! GENERATED by scripts/jac/gen_jac_flow.py — do not edit.', '',
         '# Flow invariance of law 0 (F1, STAGE_A1 §4.2)', '',
         '`flow_inv j l`: on `V(Q) × V(Q)` (any `ℚ`-algebra), with `Wn = 2W` the doubled flow quadratics',
         '(`∂_{z_j}(X_i/X₀) = W_{ji}(X)/X₀²`), `B = X₁Y₀ − X₀Y₁ + X₂Y₃ − X₃Y₂` and `A_l = 32 A_l^{(0)}`:',
         '`B · (Y₀ Σ_i Wn_{ji}(X) ∂A_l/∂X_i − X₀ Σ_i Wn_{ji}(Y) ∂A_l/∂Y_i) = 3 · GB_j · A_l`,',
         'i.e. `A_l(X̂, Ŷ)/B(X̂, Ŷ)³` is constant along `(u, v) ↦ (u + t e_j, v − t e_j)`. The formal partial derivatives',
         'are `dXsp`, `dYsp`; `hasDerivAt_evalSP` (in `LSG.Jac.Deriv`) is their calculus meaning. -/', '',
         'namespace LSG.Jac', '', 'open Data Cert Finset', '',
         'variable {R : Type*} [CommRing R]', '',
         '/-- `B(x, y) = x₁y₀ − x₀y₁ + x₂y₃ − x₃y₂` (ABVAR A0.2). -/',
         'def Bf (x y : Fin 9 → R) : R := x 1 * y 0 - x 0 * y 1 + x 2 * y 3 - x 3 * y 2', '',
         '/-- The doubled flow quadratics `Wn j i = 2 W_{j+1, i}` (`j = 0, 1` for `∂/∂z₀`, `∂/∂z₁`; zero for',
         '`i = 0` and out of range). -/',
         'def Wn (x : Fin 9 → R) : ℕ → ℕ → R']
    for j in (0, 1):
        for i in range(1, 9):
            S.append(f'  | {j}, {i} => {wn_lean(j, i, "x")}')
    S += ['  | _, _ => 0', '',
          '/-- `GB j = Y₀ Σ_i Wn_{ji}(X) ∂B/∂X_i − X₀ Σ_i Wn_{ji}(Y) ∂B/∂Y_i`. -/',
          'def GBf (x y : Fin 9 → R) (j : ℕ) : R :=',
          '  y 0 * (y 0 * Wn x j 1 + y 3 * Wn x j 2 - y 2 * Wn x j 3) -',
          '    x 0 * (-(x 0 * Wn y j 1) - x 3 * Wn y j 2 + x 2 * Wn y j 3)', '']
    for j in (0, 1):
        for i in range(1, 9):
            S += [f'lemma eval_BYW{j}{i} (x y : Fin 9 → R) : evalSP x y BYW{j}{i} = Bf x y * y 0 * Wn x {j} {i} := by',
                  f'  simp [BYW{j}{i}, evalSP, evalRow, xmono, digit, Fin.prod_univ_succ, sval, Bf, Wn]; ring', '',
                  f'lemma eval_BXW{j}{i} (x y : Fin 9 → R) : evalSP x y BXW{j}{i} = Bf x y * x 0 * Wn y {j} {i} := by',
                  f'  simp [BXW{j}{i}, evalSP, evalRow, xmono, digit, Fin.prod_univ_succ, sval, Bf, Wn]; ring', '']
        S += [f'lemma eval_GBsp{j} (x y : Fin 9 → R) : evalSP x y GBsp{j} = GBf x y {j} := by',
              f'  simp [GBsp{j}, evalSP, evalRow, xmono, digit, Fin.prod_univ_succ, sval, GBf, Wn]; ring', '']
    S += ['variable [Algebra ℚ R]', '']
    for j in (0, 1):
        for l in range(9):
            n = f'f1_{j}_{l}'
            ev = ', '.join([f'eval_BYW{j}{i}, eval_BXW{j}{i}' for i in range(1, 9)] + [f'eval_GBsp{j}'])
            S += [f'theorem flow_inv_{j}_{l} (x y : Fin 9 → R) (hx : OnQ x) (hy : OnQ y) :',
                  f'    Bf x y * (y 0 * ∑ i ∈ range 9, Wn x {j} i * evalSP x y (dXsp i (law {l} 0)) -',
                  f'      x 0 * ∑ i ∈ range 9, Wn y {j} i * evalSP x y (dYsp i (law {l} 0))) =',
                  f'      3 * GBf x y {j} * A32 {l} 0 x y := by',
                  f'  have h := identity_of_check {n} {n}_O {n}_B {n}_T x y hx hy',
                  f'  simp only [{n}, evalTerms, List.map_cons, List.map_nil, List.sum_cons, List.sum_nil, {ev}] at h',
                  '  simp only [sum_range_succ, sum_range_zero, Wn, A32, Fin.val_zero]',
                  f'  simp only [sval, Bool.false_eq_true, ↓reduceIte, Nat.cast_one, Int.cast_one, Int.cast_neg,',
                  '    Nat.cast_ofNat, Int.cast_ofNat, Wn] at h',
                  f'  try simp only [Fin.isValue, show (({l} : Fin 9) : ℕ) = {l} from rfl]',
                  '  linear_combination h', '']
    S += ['/-- **Flow invariance of law 0** (F1). -/',
          'theorem flow_inv (j : ℕ) (hj : j < 2) (l : Fin 9) (x y : Fin 9 → R) (hx : OnQ x) (hy : OnQ y) :',
          '    Bf x y * (y 0 * ∑ i ∈ range 9, Wn x j i * evalSP x y (dXsp i (law l 0)) -',
          '      x 0 * ∑ i ∈ range 9, Wn y j i * evalSP x y (dYsp i (law l 0))) =',
          '      3 * GBf x y j * A32 l 0 x y := by',
          '  interval_cases j <;> fin_cases l']
    for j in (0, 1):
        for l in range(9):
            S.append(f'  · exact flow_inv_{j}_{l} x y hx hy')
    S += ['', 'end LSG.Jac', '']
    open(os.path.join(ROOT, 'LSG', 'Jac', 'Flow.lean'), 'w', encoding='utf-8').write('\n'.join(S))
    print('wrote Data/Flow.lean, Cert/F1j0.lean, Cert/F1j1.lean, Flow.lean')


