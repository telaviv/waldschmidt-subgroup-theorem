"""Stage A1: semantic files for the E1/E2 identities (UNTRUSTED generator; Lean checks the proofs).

Writes LSG/Jac/E1DA.lean (evaluation of the merged derivatives) and LSG/Jac/E1Sem_<fam>.lean (the identities in
explicit form).  Usage (from lean_lsg/): python scripts/jac/gen_jac_e1sem.py
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
from e1_data import FAMILIES, Wn, W4n, dig
ROOT = os.path.join(HERE, '..', '..', 'LSG', 'Jac')
DAFAMS = {'X0W4': (0, 'X', 'W4n', W4n, 'WX4'), 'X0W': (0, 'X', 'Wn', Wn, 'WX0'),
          'X4W4': (4, 'X', 'W4n', W4n, 'WX4'), 'Y4W4': (4, 'Y', 'W4n', W4n, 'WY4')}
FAM_DA = {'E40': 'X0W4', 'E44': 'X0W4', 'E04': 'X0W', 'F4X': 'X4W4', 'F4Y': 'Y4W4'}
HDR = ['/-', 'Copyright (c) 2026. All rights reserved.', 'Released under Apache 2.0 license.', '-/']

def da_file():
    L = HDR + ['import LSG.Jac.E1Bridge', 'import LSG.Jac.W4', 'import LSG.Jac.CheckerDeriv', 'import LSG.Jac.Diag'] + \
        [f'import LSG.Jac.Cert.DA_{f}' for f in DAFAMS] + ['',
        '/-! GENERATED by scripts/jac/gen_jac_e1sem.py — do not edit.', '',
        '# The merged derivatives of the E1 identities', '',
        '`da_<fam>_<j>_<l>`: `evalSP x y DA = Σ_i W_{in,ji}(S) · evalSP x y (∂A_l/∂S_i)` exactly (any commutative ring),',
        'with `W_in = Wn = 2W` or `W4n = 4W⁽⁴⁾` and `S = x` or `y`. -/', '',
        'namespace LSG.Jac', '', 'open Data Cert Finset', '']
    for k in range(9):
        L.append(f'lemma fin9_val_{k} : (({k} : Fin 9) : ℕ) = {k} := rfl')
    L += ['', 'variable {R : Type*} [CommRing R]', '']
    for nm, fn, side in (('WX0', 'Wn', 'X'), ('WX4', 'W4n', 'X'), ('WY4', 'W4n', 'Y')):
        v = 'x' if side == 'X' else 'y'
        for j in (0, 1):
            for i in range(9):
                L += [f'lemma eval_{nm}_{j}_{i} (x y : Fin 9 → R) : evalSP x y {nm}_{j}_{i} = {fn} {v} {j} {i} := by',
                      f'  simp [{nm}_{j}_{i}, evalSP, evalRow, xmono, digit, Fin.prod_univ_succ, sval, {fn}]',
                      '  try ring', '']
    for fam, (m, side, fn, Win, wnm) in DAFAMS.items():
        v = 'x' if side == 'X' else 'y'
        d = 'dXsp' if side == 'X' else 'dYsp'
        br = 'identity_exact32' if side == 'X' else 'identity_exact23'
        for j in (0, 1):
            for l in range(9):
                n = f'da_{fam}_{j}_{l}'
                evs = ', '.join(f'eval_{wnm}_{j}_{i}' for i in range(9))
                L += [f'theorem {n}_eval (x y : Fin 9 → R) :',
                      f'    evalSP x y DA_{fam}_{j}_{l} = ∑ i : Fin 9, {fn} {v} {j} i * evalSP x y ({d} i (law {l} {m})) := by',
                      f'  have h := {br} {n} {n}_O {n}_B {n}_T x y',
                      f'  simp only [{n}, evalTerms, List.map_cons, List.map_nil, List.sum_cons, List.sum_nil, evalSP_oneSP, {evs}] at h',
                      f'  rw [Fin.sum_univ_eq_sum_range (fun i => {fn} {v} {j} i * evalSP x y ({d} i (law {l} {m}))) 9]',
                      '  simp only [sum_range_succ, sum_range_zero]',
                      f'  simp only [sval, Bool.false_eq_true, ↓reduceIte, Nat.cast_one, Int.cast_one, Int.cast_neg, {fn}] at h ⊢',
                      '  linear_combination -h', '']
    L += ['end LSG.Jac']
    open(os.path.join(ROOT, 'E1DA.lean'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')

def sem_files():
    for fam, (m, side, Win, sin, c, Wout, sout, f) in FAMILIES.items():
        da = FAM_DA[fam]
        fout = 'Wn' if Wout is Wn else 'W4n'
        v = 'x' if side == 'X' else 'y'
        br = 'identity_X5' if side == 'X' else 'identity_Y5'
        shift = 'evalSP_shiftX' if side == 'X' else 'evalSP_shiftY'
        sh = 'shX' if side == 'X' else 'shY'
        L = HDR + ['import LSG.Jac.E1DA', 'import LSG.Jac.Cert.Shift'] + [f'import LSG.Jac.Cert.E1_{fam}_{j}' for j in (0, 1)] + ['',
             '/-! GENERATED by scripts/jac/gen_jac_e1sem.py — do not edit.', '',
             f'# Equivariance identities `{fam}` (law {m}, {side}-flow, output chart {c})', '',
             f'`e1_{fam}_<j>_<l>`: on `V(Q) × V(Q)` (any `ℚ`-algebra),',
             f'`{sout} (A_{c} · D A_l − A_l · D A_{c}) = {sin} · {v}_{f} · {fout}_(jl)(A)` with `D A = DA_{da}` (`E1DA.lean`). -/', '',
             'namespace LSG.Jac', '', 'open Data Cert Finset', '', 'variable {R : Type*} [CommRing R] [Algebra ℚ R]', '', 'set_option maxRecDepth 100000', '']
        for j in (0, 1):
            for l in range(9):
                if l == c:
                    continue
                n = f'e1_{fam}_{j}_{l}'
                shifts = sorted({[i for i in range(9) for _ in range(dig(cd, i))][0] for cd in Wout.get((j, l), {})})
                sf = 'shiftX' if side == 'X' else 'shiftY'
                rws = ', '.join(f'show evalSP x y ({sf} {f} (law {a} {m})) = {v} {f} * evalSP x y (law {a} {m}) from '
                                f'{shift} x y {f} _ {sh}_{f}_{a}_{m}' for a in shifts)
                cert = open(os.path.join(ROOT, 'Cert', f'E1_{fam}_{j}.lean'), encoding='utf-8').read()
                nr = cert.count(f'theorem {n}_R')
                pat = ' | '.join(['rfl'] * nr)
                ex = ', '.join(f'{n}_R{k}' for k in range(nr))
                L += [f'theorem {n} (x y : Fin 9 → R) (hx : OnQ x) (hy : OnQ y) :',
                      f'    ({sout} : R) * (evalSP x y (law {c} {m}) * evalSP x y DA_{da}_{j}_{l} -',
                      f'      evalSP x y (law {l} {m}) * evalSP x y DA_{da}_{j}_{c}) =',
                      f'      {sin} * {v} {f} * {fout} (fun k => evalSP x y (law k {m})) {j} {l} := by',
                      f'  have h := {br} Cert.{n} rs_{n} (by decide +kernel)',
                      f'    (by intro r hr; simp only [rs_{n}, List.mem_cons, List.mem_nil_iff, or_false] at hr',
                      f'        rcases hr with {pat}',
                      f'        exacts [{ex}])',
                      f'    {n}_B {n}_T x y hx hy',
                      f'  simp only [Cert.{n}, evalTerms, List.map_cons, List.map_nil, List.sum_cons, List.sum_nil] at h']
                if rws:
                    L += [f'  rw [{rws}] at h']
                L += [f'  simp only [sval, Bool.false_eq_true, ↓reduceIte, Nat.cast_ofNat, Int.cast_ofNat, Int.cast_neg,',
                      f'    Nat.cast_one, Int.cast_one, {fout}] at h ⊢',
                      '  simp only [' + ', '.join(f'fin9_val_{k}' for k in range(9)) + '] at h ⊢',
                      '  linear_combination h', '']
        L += ['end LSG.Jac']
        open(os.path.join(ROOT, f'E1Sem_{fam}.lean'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')

if __name__ == '__main__':
    da_file()
    sem_files()
    print('wrote E1DA.lean, E1Sem_*.lean')
