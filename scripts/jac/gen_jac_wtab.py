"""Stage A1: explicit coefficient tables of the chart-4 and chart-8 flows (UNTRUSTED generator; Lean checks).

`W4num j l a b` / `W8num j l a b` (ℤ, upper triangular in (a, b)) with `W4C j X l = Σ_a Σ_b W4num j l a b / 4 · X_a X_b`.
Writes LSG/Jac/WTables.lean.  Usage (from lean_lsg/): python scripts/jac/gen_jac_wtab.py
"""
import json, os
from fractions import Fraction
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', '..', 'LSG', 'Jac')

def load(fn):
    return {tuple(map(int, k.split(','))): {tuple(sorted(m)): Fraction(c) for m, c in v}
            for k, v in json.load(open(os.path.join(HERE, fn))).items()}

def tensor(W, chart):
    T = [[[[0] * 9 for _ in range(9)] for _ in range(9)] for _ in range(2)]
    for j in (0, 1):
        for l in range(9):
            for (a, b), c in W.get((j + 1, l), {}).items():
                v = 4 * c
                assert v.denominator == 1
                T[j][l][a][b] += int(v)
            assert all(T[j][chart][a][b] == 0 for a in range(9) for b in range(9))
    return T

def lit(T):
    def vec(xs): return '![' + ', '.join(xs) + ']'
    return vec([vec([vec([vec([str(v) for v in row]) for row in M]) for M in Tj]) for Tj in T])

def main():
    T4, T8 = tensor(load('flow_W4.json'), 4), tensor(load('flow_W8.json'), 8)
    H4 = max(abs(v) for a in T4 for b in a for c in b for v in c)
    H8 = max(abs(v) for a in T8 for b in a for c in b for v in c)
    FV = ', '.join(f'fin9_val_{k}' for k in range(9)) if False else ''
    L = ['/-', 'Copyright (c) 2026. All rights reserved.', 'Released under Apache 2.0 license.', '-/',
         'import LSG.JacAn.A1Facts', 'import LSG.Jac.W8', '',
         '/-! GENERATED by scripts/jac/gen_jac_wtab.py — do not edit.', '',
         '# Explicit coefficient tables of the chart-4 and chart-8 flows (A1Facts fields, STAGE_A3 §8)', '',
         '`W4C j X l = Σ_a Σ_b (W4num j l a b / 4) X_a X_b` (upper triangular), likewise `W8C` (chart `X₈ = 1`,',
         '`W8C j X l = W8n X j l / 4`, `W8rel`, `W8_eight`). -/', '',
         'namespace LSG.Jac', '', 'open LSG.JacAn Finset', '',
         '/-- The chart-8 flow (`= W^{(8)}`, `W8n / 4`). -/',
         'noncomputable def W8C (j : Fin 2) (X : P9) : P9 := fun i => W8n X j i / 4', '',
         '/-- The chart-4 table (numerators over 4). -/',
         f'def W4num : Fin 2 → Fin 9 → Fin 9 → Fin 9 → ℤ := {lit(T4)}', '',
         '/-- The chart-8 table (numerators over 4). -/',
         f'def W8num : Fin 2 → Fin 9 → Fin 9 → Fin 9 → ℤ := {lit(T8)}', '',
         f'theorem W4num_bound : ∀ j l a b, |W4num j l a b| ≤ ({H4} : ℕ) := by decide +kernel', '',
         f'theorem W8num_bound : ∀ j l a b, |W8num j l a b| ≤ ({H8} : ℕ) := by decide +kernel', '']
    for nm, fn in (('W4', 'W4n'), ('W8', 'W8n')):
        for j in (0, 1):
            L += [f'lemma {nm}_table_{j} (X : P9) (l : Fin 9) :',
                  f'    {fn} X {j} l / 4 = ∑ a, ∑ b, (({nm}num {j} l a b : ℂ) / (4 : ℕ)) * (X a * X b) := by',
                  f'  fin_cases l <;> simp [{fn}, {nm}num, Fin.sum_univ_succ] <;> ring', '']
        L += [f'theorem {nm}_tableN (j : Fin 2) (X : P9) (l : Fin 9) :',
              f'    {fn} X j l / 4 = ∑ a, ∑ b, (({nm}num j l a b : ℂ) / (4 : ℕ)) * (X a * X b) := by',
              f'  fin_cases j', f'  · exact {nm}_table_0 X l', f'  · exact {nm}_table_1 X l', '']
    L += ['theorem W8_eightC (j : Fin 2) (X : P9) : W8C j X 8 = 0 := by',
          '  fin_cases j <;> simp [W8C, W8n]', '',
          'theorem onQ_quadC (X : P9) (hX : OnQ X) (j : Fin 9) : quadA X j = 0 := (onQ_iff X).mp hX j', '',
          'end LSG.Jac']
    open(os.path.join(ROOT, 'WTables.lean'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print('wrote WTables.lean; H4 =', H4, 'H8 =', H8)

if __name__ == '__main__':
    main()
