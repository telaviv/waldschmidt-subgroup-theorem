"""B5: the `lci_*` statements of the A-block (UNTRUSTED generator; Lean checks the proofs).
Reads LSG/Jac/Data/B5.lean (written by gen_jac_b5.py), writes LSG/Jac/B56.lean.
Usage (from lean_lsg/): python scripts/jac/gen_jac_b56sem.py
"""
import os, re
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'LSG', 'Jac')
FS = [(0, 1, 2, 5, 6, 7), (2, 3, 4, 6, 7, 8), (1, 4, 5, 6, 7, 8), (1, 2, 3, 5, 6, 8)]
GN = [f'gQ{k}' for k in range(9)] + [f'gC{k}' for k in range(3)]
TAB = {5: ('idTree5b', 11, 'b5i5_seq', 'b5i5_len', 1287), 6: ('idTree6b', 12, 'b5i6_seq', 'b5i6_len', 3003),
       7: ('idTree7', 13, 'p7_seq', 'p7_len', 6435)}

def main():
    src = open(os.path.join(ROOT, 'Data', 'B5.lean'), encoding='utf-8').read()
    defs = {m.group(1): m.group(2) for m in re.finditer(r'noncomputable def (b5[mc]_\d+(?:_\d+)?) : List Term := idTerms (.*)', src)}
    L = ['/-', 'Copyright (c) 2026. All rights reserved.', 'Released under Apache 2.0 license.', '-/',
         'import LSG.Jac.B56Sound', 'import LSG.JacBlock.GensMv', 'import LSG.Jac.Cert.B5base', 'import LSG.Jac.Cert.P2base'] + \
        [f'import LSG.Jac.Cert.B5M_{i}' for i in range(4)] + [f'import LSG.Jac.Cert.B5C_{v}' for v in range(9)] + ['',
         '/-! GENERATED by scripts/jac/gen_jac_b56sem.py — do not edit.', '',
         '# B5: the local-complete-intersection certificate of the A-block (`AbBlock.lci_*`)', '',
         'Four local systems `(lciS i, lciF i)`: `lciF i` is six of the quadrics `gQ*` of `gensMv`, `lciS i` a cubic with',
         '`lciS i · G ∈ (lciF i)` for every generator `G` (24 nontrivial identities, `Cert/B5M_<i>`), and',
         '`X_v⁷ ∈ (gensMv) + (lciS)` for every `v` (9 identities, `Cert/B5C_<v>`). All identities are exact over `ℤ`,',
         'kernel-checked with `CheckerP2`/`P2Sound.exact_of_idSeq`, and read in `MvPolynomial (Fin 9) ℂ` at `x = X`.',
         'For `AbBlock`: `lci_s = 4`, `lci_S = lciS`, `lci_F = lciF`, and the fields are `lciA_len`, `lciA_F_le`,',
         '`lciA_mem`, `lciA_cover` (with `g = 2`, `N = 9`, `gens = gensMv`). -/', '',
         'noncomputable section', '', 'namespace LSG.Jac', '', 'open MvPolynomial LSG.JacBlock Data Cert', '',
         '/-- The variables as a point of `MvPolynomial (Fin 9) ℂ`. -/',
         'abbrev Xv : Fin 9 → MvPolynomial (Fin 9) ℂ := fun v => X v', '']
    for k in range(12):
        L += [f'lemma gRow_{k} : evalRow Xv (gRows.getD {k} []) = {GN[k]} := by',
              f'  simp [gRows, evalRow, xmono, digit, Fin.prod_univ_succ, sval, {GN[k]}, mon, map_ofNat]',
              '  ring', '']
    L += ['/-- The cubics `S_i`. -/',
          'def lciS (i : Fin 4) : MvPolynomial (Fin 9) ℂ := evalRow Xv (sRows.getD i [])', '',
          '/-- The quadric systems `F_i`. -/',
          'def lciF : Fin 4 → List (MvPolynomial (Fin 9) ℂ) := ![' +
          ', '.join('[' + ', '.join(GN[a] for a in F) + ']' for F in FS) + ']', '',
          'lemma natCast_isUnit_mv {D : ℕ} (hD : D ≠ 0) : IsUnit (D : MvPolynomial (Fin 9) ℂ) := by',
          '  rw [← map_natCast (C : ℂ →+* MvPolynomial (Fin 9) ℂ)]',
          '  exact (isUnit_iff_ne_zero.mpr (Nat.cast_ne_zero.mpr hD)).map C', '',
          'lemma gSP_eval (a : ℕ) : evalSP Xv Xv (gSP a) = evalRow Xv (gRows.getD a []) := evalSP_rowSP _ _ _', '',
          'lemma sSP_eval (i : Fin 4) : evalSP Xv Xv (sSP i) = lciS i := evalSP_rowSP _ _ _', '']
    for d, (t, dd, seq, ln, n) in TAB.items():
        L += [f'lemma exact{d} (ps : List Term) (hO : (evalOd {dd} {t} T0 ps).allZero = true)',
              f'    (hB : wsum ps * (1 * 1) < 2 ^ 128)',
              f'    (hT : ps.all (fun q => termOK2 {t} T0 q && q.a.wf && q.b.wf) = true) : evalTerms Xv Xv ps = 0 :=',
              f'  exact_of_idSeq {dd} {t} {seq} (by rw [{ln}]; norm_num) ps hO hB hT Xv Xv', '']
    # (M)
    for i, F in enumerate(FS):
        for G in range(12):
            if G in F:
                continue
            nm = f'b5m_{i}_{G}'
            args = defs[nm]
            mm = re.match(r'(\d+) \(sSP (\d+)\) \(gSP (\d+)\) (\[.*\])$', args)
            D, cs = mm.group(1), mm.group(4)
            d = 5 if G < 9 else 6
            n = len(F)
            L += [f'lemma {nm}_mem : lciS {i} * {GN[G]} ∈ Ideal.ofList (lciF {i}) := by',
                  f'  have h := mem_of_idTerms (Ideal.ofList (lciF {i})) Xv {D} (sSP {i}) (gSP {G}) {cs}',
                  f'    (natCast_isUnit_mv (by norm_num)) (exact{d} _ {nm}_O {nm}_B {nm}_T) (by',
                  '      intro p hp',
                  '      simp only [List.mem_cons, List.mem_nil_iff, or_false] at hp',
                  '      rcases hp with ' + ' | '.join(['rfl'] * n)] + \
                 [f'      · rw [gSP_eval, gRow_{a}]; exact Ideal.subset_span (by simp [lciF])' for a in F] + \
                 [f'      )',
                  f'  rwa [show evalSP Xv Xv (sSP {i}) = lciS {i} from sSP_eval {i}, gSP_eval, gRow_{G}] at h', '']
    # (C)
    L += ['/-- `J = (gensMv) + (lciS)`. -/',
          'abbrev lciJ : Ideal (MvPolynomial (Fin 9) ℂ) :=',
          '  Ideal.span {Q | Q ∈ gensMv} ⊔ Ideal.span (Set.range lciS)', '',
          'lemma gen_mem_J {Q : MvPolynomial (Fin 9) ℂ} (h : Q ∈ gensMv) : Q ∈ lciJ :=',
          '  Ideal.mem_sup_left (Ideal.subset_span h)', '',
          'lemma S_mem_J (i : Fin 4) : lciS i ∈ lciJ := Ideal.mem_sup_right (Ideal.subset_span ⟨i, rfl⟩)', '']
    for v in range(9):
        nm = f'b5c_{v}'
        args = defs[nm]
        mm = re.match(r'(\d+) \(monoSP \(7 \* 8 \^ (\d+)\)\) oneSP (\[.*\])$', args)
        D, cs = mm.group(1), mm.group(3)
        items = re.findall(r'\((b5c_\d+_[gs]\d+), ([gs])SP (\d+)\)', cs)
        L += [f'lemma {nm}_mem : (X {v} : MvPolynomial (Fin 9) ℂ) ^ 7 ∈ lciJ := by',
              f'  have h := mem_of_idTerms lciJ Xv {D} (monoSP (7 * 8 ^ {v})) oneSP {cs}',
              f'    (natCast_isUnit_mv (by norm_num)) (exact7 _ {nm}_O {nm}_B {nm}_T) (by',
              '      intro p hp',
              '      simp only [List.mem_cons, List.mem_nil_iff, or_false] at hp',
              '      rcases hp with ' + ' | '.join(['rfl'] * len(items))]
        for _, kind, idx in items:
            if kind == 'g':
                L.append(f'      · rw [gSP_eval, gRow_{idx}]; exact gen_mem_J (by simp [gensMv])')
            else:
                L.append(f'      · rw [show evalSP Xv Xv (sSP {idx}) = lciS {idx} from sSP_eval {idx}]; exact S_mem_J {idx}')
        L += ['      )',
              f'  have hx : xmono Xv (7 * 8 ^ {v}) = (X {v} : MvPolynomial (Fin 9) ℂ) ^ 7 := xmono_seven Xv {v}',
              '  rwa [evalSP_monoSP, evalSP_oneSP, mul_one, hx] at h', '']
    # field theorems
    L += ['/-- `lci_len` (`g = 2`, `N = 9`). -/',
          'theorem lciA_len : ∀ i, (lciF i).length + 2 + 1 = 9 := by',
          '  intro i; fin_cases i <;> rfl', '',
          '/-- `lci_F_le`. -/',
          'theorem lciA_F_le : ∀ i, Ideal.ofList (lciF i) ≤ Ideal.span {Q | Q ∈ gensMv} := by',
          '  intro i',
          '  refine Ideal.span_mono fun q hq => ?_',
          '  simp only [Set.mem_setOf_eq] at hq ⊢',
          '  fin_cases i <;> simp only [lciF, Fin.zero_eta, Fin.mk_one, Fin.reduceFinMk, Matrix.cons_val, List.mem_cons,',
          '    List.mem_nil_iff, or_false] at hq <;> rcases hq with ' + ' | '.join(['rfl'] * 6) + ' <;> simp [gensMv]', '',
          '/-- `lci_mem`. -/',
          'theorem lciA_mem : ∀ i, ∀ Q ∈ gensMv, lciS i * Q ∈ Ideal.ofList (lciF i) := by',
          '  intro i Q hQ',
          '  simp only [gensMv, List.mem_cons, List.mem_nil_iff, or_false] at hQ',
          '  fin_cases i <;> rcases hQ with ' + ' | '.join(['rfl'] * 12)]
    for i, F in enumerate(FS):
        for G in range(12):
            if G in F:
                L.append(f'  · exact Ideal.mul_mem_left _ _ (Ideal.subset_span (by simp [lciF]))')
            else:
                L.append(f'  · exact b5m_{i}_{G}_mem')
    L += ['', '/-- `lci_cover` (with `e = 7`). -/',
          'theorem lciA_cover : ∀ v : Fin 9, ∃ e : ℕ,',
          '    (X v : MvPolynomial (Fin 9) ℂ) ^ e ∈ Ideal.span {Q | Q ∈ gensMv} ⊔ Ideal.span (Set.range lciS) := by',
          '  intro v',
          '  refine ⟨7, ?_⟩',
          '  fin_cases v']
    for v in range(9):
        L.append(f'  · exact b5c_{v}_mem')
    L += ['', 'end LSG.Jac', '', 'end']
    open(os.path.join(ROOT, 'B56.lean'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print('wrote B56.lean')

if __name__ == '__main__':
    main()
