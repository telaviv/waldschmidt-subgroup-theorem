"""Stage A4/B5 (taken over by A1): LCI cover certificates for the A-block (UNTRUSTED generator; Lean re-checks).

Local systems i < 4: F_i = 6 of the 9 quadrics, S_i = the cubic of ((F_i) : I_A)_3 outside I_A (gamma's
scripts/jacblock/b5_S.pkl; the cover set chosen with scripts/jacblock/jacA1_b5prune.py).
  (M) D · S_i · G = Σ_k h_k F_{i,k}            for the 6 generators G ∉ F_i  (degree 5 or 6; 24 identities)
  (C) D · X_v^7 = Σ_j H_j G_j + Σ_i C_i S_i     for v < 9                     (degree 7; 9 identities)
Writes LSG/Jac/Data/B5Id5.lean, Data/B5Id6.lean (identity tables), Data/B5.lean (rows, cofactors, identities),
Cert/B5base.lean, Cert/B5M_<i>.lean, Cert/B5C_<v>.lean, B56.lean (the `lci_*` statements).
Usage (from lean_lsg/): python scripts/jac/gen_jac_b5.py
"""
import itertools, os, pickle, sys
from math import lcm
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'jacblock'))
from jb_common import Q, CUB, GENS, X, ZERO, member, deg, weight, ctx  # noqa: E402
ROOT = os.path.join(HERE, '..', '..', 'LSG', 'Jac')
HDR = ['/-', 'Copyright (c) 2026. All rights reserved.', 'Released under Apache 2.0 license.', '-/']
FS = [(0, 1, 2, 5, 6, 7), (2, 3, 4, 6, 7, 8), (1, 4, 5, 6, 7, 8), (1, 2, 3, 5, 6, 8)]
E = 7
DEPTH = {5: 11, 6: 12, 7: 13}
TREE = {5: 'idTree5b', 6: 'idTree6b', 7: 'idTree7'}

def code(e): return sum(e[i] * 8 ** i for i in range(9))

def write(path, lines):
    open(os.path.join(ROOT, path), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')

def intpoly(p):
    """p with integer coefficients: dict code -> int."""
    out = {}
    for e, c in p.to_dict().items():
        assert c.q == 1, p
        out[code(e)] = int(c.p)
    return out

def row_lit(d):
    return '[' + ', '.join(f'({c}, {abs(v)}, {"true" if v < 0 else "false"})' for c, v in sorted(d.items()) if v) + ']'

def sp_lit(d):
    return '⟨[' + ', '.join(f'({c}, [(0, {abs(v)}, {"true" if v < 0 else "false"})])' for c, v in sorted(d.items()) if v) + \
        '], [0]⟩'

def scale(cofs):
    D = 1
    for p in cofs:
        for c in p.to_dict().values():
            D = lcm(D, int(c.q))
    return D

def idtable(d, pre, tname):
    from jb_common import monos
    keys = sorted(code(e) for e in monos(d))
    L = HDR + ['import LSG.Jac.Checker', '', f'/-! GENERATED by scripts/jac/gen_jac_b5.py — identity table of degree {d}. -/',
               '', 'namespace LSG.Jac.Data', '', 'open LSG.Jac', '']
    for i, k in enumerate(keys):
        L.append(f'noncomputable def {pre}_{i} : Leaf := ⟨{k}, {i}, [({i}, 1, false)], (0, 0)⟩')
    def tree(lo, hi):
        if hi - lo == 1:
            return f'(.leaf {pre}_{lo})'
        mid = (lo + hi) // 2
        return f'(.node {keys[mid]} {tree(lo, mid)} {tree(mid, hi)})'
    L += ['', f'noncomputable def {tname} : T := ' + tree(0, len(keys)), '', 'end LSG.Jac.Data']
    return L, len(keys)

def main():
    res = pickle.load(open(os.path.join(HERE, '..', 'jacblock', 'b5_S.pkl'), 'rb'))
    S = []
    for F in FS:
        p = ctx.from_dict(res[F][1])
        D = scale([p]); p = p * D
        g = 0
        from math import gcd
        for c in p.to_dict().values():
            g = gcd(g, int(c.p))
        S.append(p / g)
    # identity tables
    for d, pre in ((5, 'b5i5'), (6, 'b5i6')):
        L, n = idtable(d, pre, TREE[d])
        write(f'Data/B5Id{d}.lean', L)
    # data
    L = HDR + ['import LSG.Jac.B56Check', '', '/-! GENERATED by scripts/jac/gen_jac_b5.py — do not edit.', '',
               'B5 data: the 12 generators (`gRows`, = `gensMv`), the 4 cubics `S_i` (`sRows`), and the identities. -/', '',
               'namespace LSG.Jac.Data', '', 'open LSG.Jac', '',
               'def gRows : List (List (Nat × Nat × Bool)) := [' + ', '.join(row_lit(intpoly(g)) for g in GENS) + ']', '',
               'def sRows : List (List (Nat × Nat × Bool)) := [' + ', '.join(row_lit(intpoly(s)) for s in S) + ']', '',
               '/-- The generator `a` as a single-copy `SP`. -/',
               'def gSP (a : Nat) : SP := rowSP (gRows.getD a [])', '',
               '/-- The cubic `S_i` as a single-copy `SP`. -/',
               'def sSP (i : Nat) : SP := rowSP (sRows.getD i [])', '']
    certs = {}
    maxw = 0
    for i, F in enumerate(FS):
        for G in range(12):
            if G in F:
                continue
            T = S[i] * GENS[G]
            cof = member(T, [Q[a] for a in F])
            assert cof is not None, (i, G)
            D = scale(cof)
            nm = f'b5m_{i}_{G}'
            for k, a in enumerate(F):
                L.append(f'noncomputable def {nm}_h{k} : SP := {sp_lit(intpoly(cof[k] * D))}')
            L.append(f'noncomputable def {nm} : List Term := idTerms {D} (sSP {i}) (gSP {G}) [' +
                     ', '.join(f'({nm}_h{k}, gSP {a})' for k, a in enumerate(F)) + ']')
            L.append('')
            certs[nm] = deg(T)
            print(nm, 'deg', deg(T), 'D', D, flush=True)
    allg = GENS + S
    for v in range(9):
        T = X[v] ** E
        cof = member(T, allg)
        assert cof is not None, v
        D = scale(cof)
        nm = f'b5c_{v}'
        parts = []
        for j in range(12):
            if cof[j] != 0:
                L.append(f'noncomputable def {nm}_g{j} : SP := {sp_lit(intpoly(cof[j] * D))}')
                parts.append(f'({nm}_g{j}, gSP {j})')
        for i in range(4):
            if cof[12 + i] != 0:
                L.append(f'noncomputable def {nm}_s{i} : SP := {sp_lit(intpoly(cof[12 + i] * D))}')
                parts.append(f'({nm}_s{i}, sSP {i})')
        L.append(f'noncomputable def {nm} : List Term := idTerms {D} (monoSP ({E} * 8 ^ {v})) oneSP [' + ', '.join(parts) + ']')
        L.append('')
        certs[nm] = E
        print(nm, 'D', D, 'nonzero', len(parts), flush=True)
    L += ['end LSG.Jac.Data']
    write('Data/B5.lean', L)
    # certificates
    base = HDR + ['import LSG.Jac.Data.B5Id5', 'import LSG.Jac.Data.B5Id6', 'import LSG.Jac.CheckerP2', '',
                  '/-! GENERATED by scripts/jac/gen_jac_b5.py — structural checks for B5. -/', '',
                  'namespace LSG.Jac.Cert', '', 'open LSG.Jac LSG.Jac.Data', '',
                  'theorem b5i5_seq : idSeqOK idTree5b.leaves 0 = true := by decide +kernel',
                  'theorem b5i5_len : idTree5b.leaves.length = 1287 := by decide +kernel',
                  'theorem b5i6_seq : idSeqOK idTree6b.leaves 0 = true := by decide +kernel',
                  'theorem b5i6_len : idTree6b.leaves.length = 3003 := by decide +kernel', '', 'end LSG.Jac.Cert']
    write('Cert/B5base.lean', base)
    def cert_lines(nm, d):
        t = TREE[d]
        return [f'theorem {nm}_O : (evalOd {DEPTH[d]} {t} T0 {nm}).allZero = true := by decide +kernel',
                f'theorem {nm}_B : wsum {nm} * (1 * 1) < 2 ^ 128 := by decide +kernel',
                f'theorem {nm}_T : {nm}.all (fun q => termOK2 {t} T0 q && q.a.wf && q.b.wf) = true := by decide +kernel', '']
    imps = ['import LSG.Jac.Data.B5', 'import LSG.Jac.Data.B5Id5', 'import LSG.Jac.Data.B5Id6', 'import LSG.Jac.Data.P2Tab', '']
    for i in range(4):
        Lc = HDR + imps + [f'/-! GENERATED by scripts/jac/gen_jac_b5.py — B5 (M) identities of system {i}. -/', '',
                           'namespace LSG.Jac.Cert', '', 'open LSG.Jac LSG.Jac.Data', '', 'set_option maxRecDepth 100000', '']
        for nm, d in certs.items():
            if nm.startswith(f'b5m_{i}_'):
                Lc += cert_lines(nm, d)
        Lc.append('end LSG.Jac.Cert')
        write(f'Cert/B5M_{i}.lean', Lc)
    for v in range(9):
        Lc = HDR + imps + [f'/-! GENERATED by scripts/jac/gen_jac_b5.py — B5 (C) identity for `X_{v}^{E}`. -/', '',
                           'namespace LSG.Jac.Cert', '', 'open LSG.Jac LSG.Jac.Data', '', 'set_option maxRecDepth 100000', '']
        Lc += cert_lines(f'b5c_{v}', E)
        Lc.append('end LSG.Jac.Cert')
        write(f'Cert/B5C_{v}.lean', Lc)
    pickle.dump({'FS': FS, 'certs': certs}, open(os.path.join(HERE, 'b5_meta.pkl'), 'wb'))
    print('done')

if __name__ == '__main__':
    main()
