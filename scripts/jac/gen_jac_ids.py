"""Stage A1c: generate the kernel-checked identity files (UNTRUSTED generator; the kernel checks everything).

Raw check files (no mathematics imported, small kernel memory):
  LSG/Jac/Cert/V2k<k>.lean   rank-one identities  A_k^(m) A_0^(0) - A_k^(0) A_0^(m) = 0 on V(Q) x V(Q), m = 1..8
  LSG/Jac/Cert/V1.lean       law 0 lands in V(Q):  Q_j(A^(0)(X, Y)) = 0,  j = 0..8
Each identity `ps` gets three `decide +kernel` theorems: `_O` (packed normal form vanishes), `_B` (weight bound),
`_T` (code pairs / well-formedness). The semantic statements are assembled in LSG/Jac/V2.lean and LSG/Jac/V1.lean.

Usage (from lean_lsg/):  python scripts/jac/gen_jac_ids.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SPIKE = os.path.join(HERE, '..', 'abvar_spike')
OUT = os.path.join(HERE, '..', '..', 'LSG', 'Jac', 'Cert')
sys.path.insert(0, HERE)
SPLIT_V1 = set()

HEADER = """import LSG.Jac.Data.Laws
import LSG.Jac.Data.Table

/-! GENERATED by scripts/jac/gen_jac_ids.py — do not edit.

{doc} -/

namespace LSG.Jac.Cert

open LSG.Jac LSG.Jac.Data

set_option maxRecDepth 100000
"""


def checks(name, ps_txt, doc):
    return f"""
/-- {doc} -/
noncomputable def {name} : List Term := {ps_txt}

theorem {name}_O : (evalO nfTree {name}).allZero = true := by decide +kernel

theorem {name}_B : wsum {name} * rowM ^ 2 < 2 ^ kb := by decide +kernel

theorem {name}_T : {name}.all (fun q => termOK nfTree q && q.a.wf && q.b.wf) = true := by decide +kernel
"""


def main():
    os.makedirs(OUT, exist_ok=True)
    for k in range(1, 9):
        body = [HEADER.format(doc=f'Rank-one identities (V2′) for `k = {k}`: `A_{k}^(m) A_0^(0) − A_{k}^(0) A_0^(m) ∈ (Q(X)) + (Q(Y))`, '
                                  f'`m = 1 … 8`.')]
        for m in range(1, 9):
            body.append(checks(f'v2_{k}_{m}', f'[⟨1, false, L{k}{m}, L00⟩, ⟨1, true, L{k}0, L0{m}⟩]',
                               f'`A_{k}^({m}) A_0^(0) − A_{k}^(0) A_0^({m})`.'))
        body.append('\nend LSG.Jac.Cert\n')
        with open(os.path.join(OUT, f'V2k{k}.lean'), 'w', encoding='utf-8') as fh:
            fh.write(''.join(body))
    quads = json.load(open(os.path.join(SPIKE, 'ideal.json')))['quadrics']
    import slots
    kb, rows = slots.load_table()
    laws = slots.load_laws()
    body = [HEADER.replace('import LSG.Jac.Data.Table', 'import LSG.Jac.Data.Table' + chr(10) +
                           'import LSG.Jac.CheckerSplit').format(
        doc='Law 0 lands in the model (V1): `Q_j(A^(0)(X, Y)) ∈ (Q(X)) + (Q(Y))`, `j = 0 … 8`. Identities with more '
            'than 3 products are split over two declarations (`LSG.Jac.CheckerSplit`) to keep kernel memory '
            '≲ 3.5 GB.')]
    for j, q in enumerate(quads):
        terms = [(abs(c), c < 0, a, b) for (a, b), c in q]
        txt = [f'⟨{c}, {"true" if ng else "false"}, L{a}0, L{b}0⟩' for c, ng, a, b in terms]
        if len(terms) <= 3:
            body.append(checks(f'v1_{j}', '[' + ', '.join(txt) + ']', f'`Q_{j}(A^(0)(X, Y))`.'))
            continue
        k = len(terms) - 2
        acc = slots.eval_slots([(c, ng, laws[(a, 0)], laws[(b, 0)]) for c, ng, a, b in terms[:k]], kb, rows)
        n = f'v1_{j}'
        body.append(f"""
/-- `Q_{j}(A^(0)(X, Y))`, first {k} products. -/
noncomputable def {n}a : List Term := [{', '.join(txt[:k])}]

/-- `Q_{j}(A^(0)(X, Y))`, remaining products. -/
noncomputable def {n}b : List Term := [{', '.join(txt[k:])}]

/-- The accumulator after `{n}a` (slot values, generated). -/
def {n}L : List (Nat × Nat) := {slots.lean_slot_list(acc)}

theorem {n}_S1 : slotsEq (evalO nfTree {n}a) {n}L = true := by decide +kernel

theorem {n}_S2 : (evalFrom nfTree nfTree (AT.ofList {n}L) {n}b).allZero = true := by decide +kernel

theorem {n}_B : wsum ({n}a ++ {n}b) * rowM ^ 2 < 2 ^ kb := by decide +kernel

theorem {n}_T : ({n}a ++ {n}b).all (fun q => termOK nfTree q && q.a.wf && q.b.wf) = true := by decide +kernel
""")
    body.append(chr(10) + 'end LSG.Jac.Cert' + chr(10))
    with open(os.path.join(OUT, 'V1.lean'), 'w', encoding='utf-8') as fh:
        fh.write(''.join(body))
    SPLIT_V1.update(j for j, q in enumerate(quads) if len(q) > 3)
    print('wrote', OUT)




# ----------------------------------------------------------------------------------------------- semantic files
SEM_OUT = os.path.join(HERE, '..', '..', 'LSG', 'Jac')


def semantic():
    quads = json.load(open(os.path.join(SPIKE, 'ideal.json')))['quadrics']
    # ---- V2.lean
    L = ['/-', 'Copyright (c) 2026. All rights reserved.', 'Released under Apache 2.0 license.', '-/']
    L += ['import LSG.Jac.Laws'] + [f'import LSG.Jac.Cert.V2k{k}' for k in range(1, 9)]
    L += ['', '/-! GENERATED by scripts/jac/gen_jac_ids.py — do not edit.', '',
          '# The rank-one identities (V2′, ABVAR §A0.3)', '',
          'For all `k, m`: `A_k^(m)(x, y) A_0^(0)(x, y) = A_k^(0)(x, y) A_0^(m)(x, y)` on `V(Q) × V(Q)`, over any',
          '`ℚ`-algebra (`rank_one`). The 64 nontrivial cases `k, m ∈ 1 … 8` are kernel checks (`LSG.Jac.Cert.V2k*`);',
          'the others are trivial. -/', '',
          'namespace LSG.Jac', '', 'open Data Cert', '',
          'variable {R : Type*} [CommRing R]', '',
          'lemma evalTerms_pair (x y : Fin 9 → R) (a b c d : SP) :',
          '    evalTerms x y [⟨1, false, a, b⟩, ⟨1, true, c, d⟩] =',
          '      evalSP x y a * evalSP x y b - evalSP x y c * evalSP x y d := by',
          '  simp [evalTerms, sval, sub_eq_add_neg]', '', 'variable [Algebra ℚ R]', '']
    for k in range(1, 9):
        for m in range(1, 9):
            n = f'v2_{k}_{m}'
            L += [f'theorem rank_one_{k}_{m} (x y : Fin 9 → R) (hx : OnQ x) (hy : OnQ y) :',
                  f'    A32 {k} {m} x y * A32 0 0 x y = A32 {k} 0 x y * A32 0 {m} x y := by',
                  f'  have h := identity_of_check {n} {n}_O {n}_B {n}_T x y hx hy',
                  f'  rw [{n}, evalTerms_pair] at h',
                  '  exact sub_eq_zero.mp h', '']
    L += ['/-- **Rank one** (V2′): `A_k^(m) A_0^(0) = A_k^(0) A_0^(m)` on `V(Q) × V(Q)`. -/',
          'theorem rank_one (k m : Fin 9) (x y : Fin 9 → R) (hx : OnQ x) (hy : OnQ y) :',
          '    A32 k m x y * A32 0 0 x y = A32 k 0 x y * A32 0 m x y := by',
          '  fin_cases k <;> fin_cases m']
    for k in range(9):
        for m in range(9):
            if k == 0 or m == 0:
                L.append('  · first | rfl | (simp only [Fin.zero_eta, Fin.isValue]; ring) | simp only [Fin.zero_eta, Fin.isValue]')
            else:
                L.append(f'  · exact rank_one_{k}_{m} x y hx hy')
    L += ['', 'end LSG.Jac', '']
    with open(os.path.join(SEM_OUT, 'V2.lean'), 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(L))
    # ---- V1.lean
    L = ['/-', 'Copyright (c) 2026. All rights reserved.', 'Released under Apache 2.0 license.', '-/',
         'import LSG.Jac.Laws', 'import LSG.Jac.Model', 'import LSG.Jac.Cert.V1', '',
         '/-! GENERATED by scripts/jac/gen_jac_ids.py — do not edit.', '',
         '# Law 0 maps the model to the model (V1 for `m = 0`, ABVAR §A0.3)', '',
         '`law0_onQ`: for `x, y ∈ V(Q)` over any `ℚ`-algebra, `A^(0)(x, y) ∈ V(Q)` (9 kernel checks,',
         '`LSG.Jac.Cert.V1`). -/', '',
         'namespace LSG.Jac', '', 'open Data Cert', '',
         'variable {R : Type*} [CommRing R]', '']
    for k in range(9):
        L += [f'lemma A32_{k}_0 (x y : Fin 9 → R) : A32 {k} 0 x y = evalSP x y L{k}0 := rfl', '']
    L += ['variable [Algebra ℚ R]', '']
    for j in range(9):
        n = f'v1_{j}'
        nq = len(quads[j])
        if nq <= 3:
            hl = [f'  have h := identity_of_check {n} {n}_O {n}_B {n}_T x y hx hy',
                  f'  simp [{n}, evalTerms, sval] at h']
        else:
            hl = [f'  have h := identity_of_check_split {n}a {n}b {n}L {n}_S1 {n}_S2 {n}_B {n}_T x y hx hy',
                  f'  simp [{n}a, {n}b, evalTerms, sval] at h']
        L += [f'theorem law0_quad_{j} (x y : Fin 9 → R) (hx : OnQ x) (hy : OnQ y) : quad (lawPt 0 x y) {j} = 0 := by'] + hl + [
              '  simp only [quad, lawPt, Matrix.cons_val, Fin.isValue] at ⊢',
              '  simp only [' + ', '.join(f'A32_{k}_0' for k in range(9)) + ']',
              '  linear_combination h', '']
    L += ['/-- **Law 0 lands in the model** (V1, `m = 0`). -/',
          'theorem law0_onQ (x y : Fin 9 → R) (hx : OnQ x) (hy : OnQ y) : OnQ (lawPt 0 x y) := by',
          '  rw [onQ_iff]', '  intro j', '  fin_cases j']
    for j in range(9):
        L.append(f'  · exact law0_quad_{j} x y hx hy')
    L += ['', 'end LSG.Jac', '']
    with open(os.path.join(SEM_OUT, 'V1.lean'), 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(L))
    print('wrote semantic files')


if __name__ == '__main__':
    main()
    semantic()
