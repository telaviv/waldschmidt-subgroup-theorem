"""Stage A1: V1 for law m (default 4): Q_j(A^(m)(X, Y)) in (Q(X)) + (Q(Y)), j = 0..8, split like Cert/V1.lean.
Writes LSG/Jac/Cert/V1L<m>.lean and LSG/Jac/V1L<m>.lean (with `law<m>_onQ`, and `dup_onQ` for m = 4).
UNTRUSTED generator. Usage: python scripts/jac/gen_jac_v1m.py [m]"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import slots
ROOT = os.path.join(HERE, '..', '..')
m = int(sys.argv[1]) if len(sys.argv) > 1 else 4
quads = json.load(open(os.path.join(HERE, '..', 'abvar_spike', 'ideal.json')))['quadrics']
kb, rows = slots.load_table(); laws = slots.load_laws()
PARTS = {}
C = ['import LSG.Jac.Data.Laws', 'import LSG.Jac.Data.Table', 'import LSG.Jac.CheckerSplit', '',
     '/-! GENERATED by scripts/jac/gen_jac_v1m.py — do not edit.', '',
     f'Law {m} lands in the model: `Q_j(A^({m})(X, Y)) ∈ (Q(X)) + (Q(Y))`, `j = 0 … 8` (split like `Cert/V1`). -/', '',
     'namespace LSG.Jac.Cert', '', 'open LSG.Jac LSG.Jac.Data', '', 'set_option maxRecDepth 100000', '']
for j, q in enumerate(quads):
    terms = [(abs(c), c < 0, a, b) for (a, b), c in q]
    txt = [f'⟨{c}, {"true" if ng else "false"}, L{a}{m}, L{b}{m}⟩' for c, ng, a, b in terms]
    n = f'v1m{m}_{j}'
    chunks = [terms[i:i + 2] for i in range(0, len(terms), 2)]
    tchunks = [txt[i:i + 2] for i in range(0, len(txt), 2)]
    PARTS[j] = len(chunks)
    if len(chunks) == 1:
        C += [f'noncomputable def {n} : List Term := [{", ".join(txt)}]', '',
              f'theorem {n}_O : (evalO nfTree {n}).allZero = true := by decide +kernel', '',
              f'theorem {n}_B : wsum {n} * rowM ^ 2 < 2 ^ kb := by decide +kernel', '',
              f'theorem {n}_T : {n}.all (fun q => termOK nfTree q && q.a.wf && q.b.wf) = true := by decide +kernel', '']
        continue
    names = [f'{n}{chr(97 + i)}' for i in range(len(chunks))]
    for nm, tc in zip(names, tchunks):
        C += [f'noncomputable def {nm} : List Term := [{", ".join(tc)}]', '']
    acc = {}
    for i in range(len(chunks) - 1):
        acc = slots.eval_slots([(c, ng, laws[(a, m)], laws[(b, m)]) for c, ng, a, b in chunks[i]], kb, rows, acc)
        C += [f'def {n}L{i + 1} : List (Nat × Nat) := {slots.lean_slot_list(acc)}', '']
    C += [f'theorem {n}_S1 : slotsEq (evalO nfTree {names[0]}) {n}L1 = true := by decide +kernel', '']
    for i in range(1, len(chunks) - 1):
        C += [f'theorem {n}_S{i + 1} : slotsEq (evalFrom nfTree nfTree (AT.ofList {n}L{i}) {names[i]}) {n}L{i + 1} = true := by decide +kernel', '']
    k = len(chunks) - 1
    C += [f'theorem {n}_Z : (evalFrom nfTree nfTree (AT.ofList {n}L{k}) {names[k]}).allZero = true := by decide +kernel', '']
    allps = ' ++ '.join(names)
    C += [f'theorem {n}_B : wsum ({allps}) * rowM ^ 2 < 2 ^ kb := by decide +kernel', '',
          f'theorem {n}_T : ({allps}).all (fun q => termOK nfTree q && q.a.wf && q.b.wf) = true := by decide +kernel', '']
C += ['end LSG.Jac.Cert', '']
open(os.path.join(ROOT, 'LSG', 'Jac', 'Cert', f'V1L{m}.lean'), 'w', encoding='utf-8').write('\n'.join(C))
S = ['/-', 'Copyright (c) 2026. All rights reserved.', 'Released under Apache 2.0 license.', '-/',
     'import LSG.Jac.Laws', 'import LSG.Jac.Model', f'import LSG.Jac.Cert.V1L{m}', '',
     '/-! GENERATED by scripts/jac/gen_jac_v1m.py — do not edit.', '',
     f'# Law {m} maps the model to the model', '',
     f'`law{m}_onQ`: for `x, y ∈ V(Q)` (any `ℚ`-algebra), `A^({m})(x, y) ∈ V(Q)`' +
     ('; hence `dup_onQ`.' if m == 4 else '.') + ' -/', '',
     'namespace LSG.Jac', '', 'open Data Cert', '', 'variable {R : Type*} [CommRing R]', '']
for k in range(9):
    S += [f'lemma A32_{k}_{m} (x y : Fin 9 → R) : A32 {k} {m} x y = evalSP x y L{k}{m} := rfl', '']
S += ['variable [Algebra ℚ R]', '']
for j, q in enumerate(quads):
    n = f'v1m{m}_{j}'
    np_ = PARTS[j]
    if np_ == 1:
        hl = [f'  have h := identity_of_check {n} {n}_O {n}_B {n}_T x y hx hy', f'  simp [{n}, evalTerms, sval] at h']
    elif np_ == 2:
        hl = [f'  have h := identity_of_check_split {n}a {n}b {n}L1 {n}_S1 {n}_Z {n}_B {n}_T x y hx hy',
              f'  simp [{n}a, {n}b, evalTerms, sval] at h']
    else:
        hl = [f'  have h := identity_of_check_split3 {n}a {n}b {n}c {n}L1 {n}L2 {n}_S1 {n}_S2 {n}_Z {n}_B {n}_T x y hx hy',
              f'  simp [{n}a, {n}b, {n}c, evalTerms, sval] at h']
    S += [f'theorem law{m}_quad_{j} (x y : Fin 9 → R) (hx : OnQ x) (hy : OnQ y) : quad (lawPt {m} x y) {j} = 0 := by'] + hl + [
          '  simp only [quad, lawPt, Matrix.cons_val, Fin.isValue] at ⊢',
          '  simp only [' + ', '.join(f'A32_{k}_{m}' for k in range(9)) + ']', '  linear_combination h', '']
S += [f'/-- **Law {m} lands in the model.** -/',
      f'theorem law{m}_onQ (x y : Fin 9 → R) (hx : OnQ x) (hy : OnQ y) : OnQ (lawPt {m} x y) := by',
      '  rw [onQ_iff]', '  intro j', '  fin_cases j'] + [f'  · exact law{m}_quad_{j} x y hx hy' for j in range(9)] + ['']
if m == 4:
    S += ['/-- **`dup` preserves the model.** -/',
          'theorem dup_onQ (x : Fin 9 → R) (hx : OnQ x) : OnQ (dup x) := law4_onQ x x hx hx', '']
S += ['end LSG.Jac', '']
open(os.path.join(ROOT, 'LSG', 'Jac', f'V1L{m}.lean'), 'w', encoding='utf-8').write('\n'.join(S))
print('wrote', m)
