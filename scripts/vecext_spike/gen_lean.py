def lean(e):
    s = sp.sstr(sp.expand(e), order='lex')
    s = s.replace('**', '^')
    s = re.sub(r'\b(U1|V1|W1|U2|V2|W2|g2|g3|x1|y1|x2|y2)\b', lambda m: SUB[m.group(1)], s)
    return s

def wrap(s, indent, first=0, width=100):
    """wrap at ' + ' / ' - ' boundaries"""
    toks = re.split(r'( [+-] )', s)
    lines, cur = [], toks[0]
    i = 1
    lim = width - indent
    curlim = width - first
    while i < len(toks):
        op, t = toks[i], toks[i + 1]
        if len(cur) + len(op) + len(t) > curlim:
            lines.append(cur)
            cur = op.strip() + ' ' + t
            curlim = lim
        else:
            cur += op + t
        i += 2
    lines.append(cur)
    return ('\n' + ' ' * indent).join(lines)

