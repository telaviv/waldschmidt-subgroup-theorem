"""A4 spike (UNTRUSTED, mod p): do the invariant flows leave the boundary {X_0 = 0} of V(Q) at every point?

For a chart c (X_c != 0) with quadratic chart field W^[c] (charts_modp.py), let J^[c] be generated by X_0 and the
symmetrised derivatives of X_0 of order <= 3 (D_1, D_2 the chart-c fields; the sums of all words with a given
number of D_1's, i.e. the coefficients of D_v^k X_0 in v).  Since X_0 vanishes
to order exactly 3 along Theta, we expect X_c^N in I_A + J^[c] for some N: then every boundary point with X_c != 0
moves into the affine part along some flow line, which reduces surjectivity at the boundary to the affine case
(closedness of E(C^2)).  We report the least such N per chart (rank test in (S/I_A)_N by evaluation at points).
Usage: python boundary_flow_modp.py Nmax
"""
import itertools, json, os, sys, random
import flint, sympy as sp
HERE = os.path.dirname(os.path.abspath(__file__))
JAC = os.path.join(HERE, '..', 'jac')
sys.path.insert(0, JAC)
from g1_measure import chart_pt, Xof, P, ratrec
SPIKE = os.path.join(HERE, '..', 'abvar_spike')
lq = json.load(open(os.path.join(SPIKE, 'laws_Q.json')))
std2 = [tuple(s) for s in lq['std']]
W = {tuple(map(int, k.split(','))): {tuple(m): sp.Rational(c) for m, c in v}
     for k, v in json.load(open(os.path.join(JAC, 'flow_W.json'))).items()}
Xs = sp.symbols('X0:9')
Nmax = int(sys.argv[1])


def fr(c):
    c = sp.Rational(c)
    return int(c.p) * pow(int(c.q), -1, P) % P


def Wpoly(j, i):
    return sum(c * Xs[a] * Xs[b] for (a, b), c in W.get((j, i), {}).items()) if i > 0 else sp.Integer(0)


random.seed(13)
pts = [Xof(chart_pt()[0]) for _ in range(9 * Nmax * Nmax + 80)]
rowsA = [[X[a] * X[b] % P for a, b in std2] for X in pts[:160]]


def chart_field(c):
    F = {}
    for j in (1, 2):
        for i in range(9):
            rhs = [(X[c] * fr(Wpoly(j, i).subs(dict(zip(Xs, X)))) - X[i] * fr(Wpoly(j, c).subs(dict(zip(Xs, X))))) % P
                   for X in pts[:160]]
            M = flint.nmod_mat([r + [v] for r, v in zip(rowsA, rhs)], P)
            R, rk = M.rref()
            poly = sp.Integer(0)
            for r in range(rk):
                piv = next(cc for cc in range(len(std2)) if int(R[r, cc]) != 0)
                v = ratrec(int(R[r, len(std2)]))
                assert v is not None
                a, b = std2[piv]
                poly += v * Xs[a] * Xs[b]
            F[(j, i)] = poly
    return F


def evalp(poly, X):
    f = sp.lambdify(Xs, poly, 'math')
    return None


def monos(d):
    return list(itertools.combinations_with_replacement(range(9), d))


def ev_mono(x, m):
    r = 1
    for i in m:
        r = r * x[i] % P
    return r


for c in range(1, 9):
    Wc = chart_field(c)
    D = lambda j, F: sp.expand(sum(Wc[(j, i)] * sp.diff(F, Xs[i]) for i in range(9)))
    # symmetrised words only (pure powers D_v^k of one direction field v = v1 D1 + v2 D2, by polarisation): these
    # are the Taylor coefficients of X_0 along a single real-time flow line, which is what the analytic step uses
    words = {(): Xs[0]}
    for k in range(1, 4):
        for w in itertools.product((1, 2), repeat=k):
            words[w] = D(w[0], words[w[1:]])
    gens = [Xs[0]]
    for k in range(1, 4):
        for n1 in range(k + 1):
            gens.append(sp.expand(sum(words[w] for w in itertools.product((1, 2), repeat=k) if w.count(1) == n1)))
    gens = [g for g in gens if g != 0]
    polys = [sp.Poly(g, *Xs) for g in gens]

    def evpoly(pl, x):
        s = 0
        for mon, co in pl.terms():
            t = fr(co)
            for i, e in enumerate(mon):
                if e:
                    t = t * pow(x[i], e, P)
            s += t
        return s % P
    found = None
    for N in range(4, Nmax + 1):
        npts = 9 * N * N + 40
        gv = [([evpoly(pl, x) for x in pts[:npts]], pl.total_degree()) for pl in polys]
        rows = []
        for vals, d in gv:
            if d > N:
                continue
            for m in monos(N - d):
                rows.append([vals[t] * ev_mono(pts[t], m) % P for t in range(npts)])
        M = flint.nmod_mat(rows, P)
        rk = M.rank()
        target = [pow(x[c], N, P) for x in pts[:npts]]
        rk2 = flint.nmod_mat(rows + [target], P).rank()
        print(f'chart X{c}: N = {N}: rank J_N on A = {rk} / {9 * N * N}; X_{c}^N in I + J: {rk2 == rk}', flush=True)
        if rk2 == rk:
            found = N
            break
    print(f'chart X{c}: least N = {found}  (generator degrees: {sorted(pl.total_degree() for pl in polys)})', flush=True)
