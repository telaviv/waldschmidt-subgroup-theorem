"""A0b step 2: the homogeneous ideal I(J) of Grant's P^8 model in degrees d = 2..DMAX (exact over Q).

Method: a degree-d monomial in X_0..X_8 is a polynomial in the Mumford coordinates; its normal form modulo the Mumford
relations (Groebner basis, grevlex, sympy, exact) is a vector over Q; I_d = kernel of the normal-form map (exact,
flint fmpq_mat).  Expected (projective normality, h^0(3d Theta) = 9 d^2): dim S_d/I_d = 9 d^2, i.e.
dim I_2 = 45 - 36 = 9, dim I_3 = 165 - 81 = 84, dim I_4 = 495 - 144 = 351.
We also compute dim (Q)_d (the degree-d part of the ideal generated by the quadrics) to see whether cubics are needed.

Output: ideal.json with the quadric basis (integer coefficients, reduced echelon form) and the dimension table.
Usage: python ideal_P8.py [DMAX=4]
"""
import itertools
import json
import sys
import time
from fractions import Fraction
import sympy as sp
import flint
from jac import load_model

s1, s2, b1, b0 = sp.symbols('s1 s2 b1 b0')
MUM = (s1, s2, b1, b0)


def setup():
    m = load_model()
    env = {'s1': s1, 's2': s2, 'b1': b1, 'b0': b0}
    X = [sp.sympify(e, locals=env) for e in m['X']]
    rel = [sp.sympify(e, locals=env) for e in m['relations']]
    G = sp.groebner(rel, *MUM, order='grevlex', domain='QQ')
    return X, G


def nf_table(X, G, d, cache):
    monos = list(itertools.combinations_with_replacement(range(9), d))
    rows = []
    for mono in monos:
        key = mono
        # build from cached degree-(d-1) normal form times X_last, then reduce
        if d == 1:
            e = X[mono[0]]
        else:
            e = sp.expand(cache[mono[:-1]] * X[mono[-1]])
        nf = G.reduce(e)[1]
        cache[key] = sp.expand(nf)
        rows.append(sp.Poly(cache[key], *MUM).as_dict())
    return monos, rows


def kernel_Q(rows):
    allm = sorted({k for r in rows for k in r})
    idx = {k: i for i, k in enumerate(allm)}
    M = flint.fmpq_mat(len(rows), len(allm))
    for i, r in enumerate(rows):
        for k, v in r.items():
            M[i, idx[k]] = flint.fmpq(int(sp.numer(v)), int(sp.denom(v)))
    # left kernel: solve v^T M = 0  <=> M^T v = 0
    Mt = M.transpose()
    rref, rank = Mt.rref()
    n = Mt.ncols()
    pivots = []
    r = 0
    for c in range(n):
        if r < rank and rref[r, c] != 0:
            pivots.append(c)
            r += 1
    free = [c for c in range(n) if c not in pivots]
    basis = []
    for fc in free:
        v = [flint.fmpq(0)] * n
        v[fc] = flint.fmpq(1)
        for i, pc in enumerate(pivots):
            v[pc] = -rref[i, fc]
        basis.append(v)
    return rank, basis


def to_int_vec(v):
    from math import lcm, gcd
    L = 1
    for x in v:
        L = lcm(L, int(x.q))
    w = [int(x * L) for x in v]
    g = 0
    for x in w:
        g = gcd(g, x)
    return [x // g for x in w]


def span_dim_generated(quads_monos, quads, d):
    """dim of (Q)_d = span{ m * q : deg m = d - 2 } inside S_d."""
    monos_d = list(itertools.combinations_with_replacement(range(9), d))
    idx = {m: i for i, m in enumerate(monos_d)}
    rows = []
    for m in itertools.combinations_with_replacement(range(9), d - 2):
        for q in quads:
            row = {}
            for qm, c in q.items():
                mm = tuple(sorted(m + qm))
                row[idx[mm]] = row.get(idx[mm], 0) + c
            rows.append(row)
    M = flint.fmpq_mat(len(rows), len(monos_d))
    for i, r in enumerate(rows):
        for k, v in r.items():
            M[i, k] = v
    return M.rank()


def main():
    DMAX = int(sys.argv[1]) if len(sys.argv) > 1 else 4
    X, G = setup()
    cache = {}
    table = {}
    quads = None
    out = {}
    for d in range(1, DMAX + 1):
        t0 = time.time()
        monos, rows = nf_table(X, G, d, cache)
        rank, ker = kernel_Q(rows)
        table[d] = dict(monomials=len(monos), quotient=rank, ideal=len(ker))
        print(f'd={d}: #monomials={len(monos)} dim S_d/I_d={rank} (expect {9 * d * d if d else 1}) '
              f'dim I_d={len(ker)}  [{time.time() - t0:.1f}s]', flush=True)
        if d == 2:
            quads = []
            for v in ker:
                w = to_int_vec(v)
                quads.append({monos[i]: c for i, c in enumerate(w) if c})
            out['quadrics'] = [[[list(m), c] for m, c in q.items()] for q in quads]
            for q in quads:
                print('   Q:', ' + '.join(f'{c}*' + '*'.join(f'X{i}' for i in m) for m, c in q.items()))
        if d >= 3 and quads is not None:
            g = span_dim_generated(None, quads, d)
            table[d]['generated_by_quadrics'] = g
            print(f'   dim (Q)_{d} = {g}  (need {len(ker)})', flush=True)
            if d == 3 and g < len(ker):
                # cubics needed: pick kernel vectors not in (Q)_3 later if necessary
                cub = []
                for v in ker:
                    cub.append({monos[i]: c for i, c in enumerate(to_int_vec(v)) if c})
                out['I3_basis'] = [[[list(m), c] for m, c in q.items()] for q in cub]
    out['table'] = table
    with open('ideal.json', 'w') as fh:
        json.dump(out, fh, indent=1)


if __name__ == '__main__':
    main()
