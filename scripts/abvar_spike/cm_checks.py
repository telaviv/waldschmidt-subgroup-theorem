"""ABVAR spike: small checks behind ABVAR.md section 1 and section 2 (no Lean).

1. Hyperelliptic form: on y^N = x(1-x), u = 2x - 1 gives u^2 = 1 - 4y^N and dx/y^k = -N y^(N-1-k) dy/u (exact, sympy).
2. CM types: Phi_5 = {1,2} (dx/y^4, dx/y^3), Phi_7 = {1,2,3} (dx/y^6, dx/y^5, dx/y^4) are primitive (trivial stabiliser in
   (Z/N)^x), and the Boolean algebra generated by the translates a*Phi separates all embeddings (the linear-algebra input
   of "abelian subvarieties of A^r <-> F-subspaces of F^r").
3. The period matrix of A^natural (N = 5: all four eigen-differentials dx/y^k, k = 4,3,2,1, on the cycles [zeta^e] gamma,
   e = 0..3) is nonsingular: it is diag(P_k) times a Vandermonde matrix in zeta^{-k}. This is the CM "Legendre relation"
   needed for T(A^natural) = C-span of its periods (cf. legendre_ne_zero in the elliptic case).
4. Euler-Jacobi identity (local Abel theorem): sum_i x_i^k / R'(x_i) = 0 for k <= deg R - 2 (numerical, random R).

Usage: python cm_checks.py
"""
import itertools
import random
import mpmath as mp
import sympy as sp

mp.mp.dps = 40


def check_hyperelliptic(N):
    x, y, u = sp.symbols('x y u')
    # u = 2x - 1  =>  u^2 - (1 - 4 x (1 - x)) = 0 identically
    assert sp.expand((2 * x - 1) ** 2 - (1 - 4 * x * (1 - x))) == 0
    # dx = du/2, and differentiating u^2 = 1 - 4y^N: 2u du = -4N y^(N-1) dy  =>  dx = -N y^(N-1) dy / u
    for k in range(1, N):
        lhs = (-N * y ** (N - 1) / u) / y ** k
        rhs = -N * y ** (N - 1 - k) / u
        assert sp.simplify(lhs - rhs) == 0
    return True


def cm_type_checks(N, Phi):
    units = [a for a in range(1, N) if sp.gcd(a, N) == 1]
    stab = [a for a in units if sorted((a * p) % N for p in Phi) == sorted(Phi)]
    translates = [frozenset((a * p) % N for p in Phi) for a in units]
    # atoms of the Boolean algebra generated by the translates
    atoms = set()
    for e in units:
        atom = frozenset(units)
        for T in translates:
            atom = atom & (T if e in T else frozenset(units) - T)
        atoms.add(atom)
    return stab, sorted(map(sorted, atoms))


def period_matrix_det(N, ks):
    zeta = mp.exp(2j * mp.pi / N)
    # P_k = (1 - zeta^{-k}) B(1 - k/N, 1 - k/N): integral of dx/y^k over gamma = l - [zeta] l, [zeta]^* dx/y^k = zeta^{-k}
    P = {k: (1 - zeta ** (-k)) * mp.beta(1 - mp.mpf(k) / N, 1 - mp.mpf(k) / N) for k in ks}
    M = mp.matrix(len(ks), len(ks))
    for i, e in enumerate(range(len(ks))):
        for j, k in enumerate(ks):
            M[i, j] = zeta ** (-k * e) * P[k]
    return mp.det(M), P


def euler_jacobi(trials=5):
    worst = 0
    for _ in range(trials):
        n = random.randint(3, 9)
        roots = [mp.mpc(random.random(), random.random()) for _ in range(n)]
        for k in range(n - 1):
            s = 0
            for i, r in enumerate(roots):
                d = mp.mpf(1)
                for j, r2 in enumerate(roots):
                    if j != i:
                        d *= (r - r2)
                s += r ** k / d
            worst = max(worst, abs(s))
    return worst


