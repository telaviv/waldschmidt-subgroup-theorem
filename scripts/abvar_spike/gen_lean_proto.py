"""A0b step 8: generate a Lean prototype of ONE membership certificate (law m, quadric j), kernel-checked by
`decide +kernel` with a small sparse-polynomial evaluator over Z (no Mathlib needed for the check itself).

Identity (scaled to integers):  S * Q_j(A^{(m)}(X,Y)) = sum_i S c_i Q_i(X) + sum_i S d_i Q_i(Y),
with A scaled by 32 (so Q_j(32 A) = 1024 Q_j(A)) and S = 1024 * den(cofactors).
Monomials in 18 variables (X0..X8, Y0..Y8), exponent < 8, encoded as sum e_i 8^i.

Usage: python gen_lean_proto.py m j OUTDIR [variant]
   variant 'tree' (default): products by pairwise (balanced) merging;  'fold': products by left fold.
Writes OUTDIR/AbvarProto/Cert_m<m>_j<j>.lean
"""
import json
import os
import sys
from fractions import Fraction
from math import lcm

CH = 200


def code(e):
    return sum(int(x) * 8 ** i for i, x in enumerate(e))


def poly_from_terms(terms):
    return {code(e): Fraction(c) for e, c in terms}


def lean_list(name, items, out):
    """Emit a Poly as chunks; items sorted by code."""
    chunks = [items[i:i + CH] for i in range(0, len(items), CH)] or [[]]
    names = []
    for ci, ch in enumerate(chunks):
        nm = f'{name}_{ci}'
        names.append(nm)
        body = ', '.join(f'({k}, {v})' for k, v in ch)
        out.append(f'def {nm} : Poly := [{body}]')
    out.append(f'def {name} : Poly := ' + ' ++ '.join(names))


def main():
    m, j = int(sys.argv[1]), int(sys.argv[2])
    outdir = sys.argv[3]
    variant = sys.argv[4] if len(sys.argv) > 4 else 'tree'
    lq = json.load(open('laws_Q.json'))
    quads = json.load(open('ideal.json'))['quadrics']
    cert = json.load(open(f'cert_m{m}_j{j}.json'))
    A = []
    for k in range(9):
        terms = [(e, Fraction(c)) for e, c in lq['laws'][f'{k},{m}']]
        A.append({code(e): c * 32 for e, c in terms})
    for a in A:
        for v in a.values():
            assert v.denominator == 1
    den = 1
    for pl in cert['cX'] + cert['dY']:
        for e, c in pl:
            den = lcm(den, Fraction(c).denominator)
    S = 1024 * den
    cX = [{code(e): Fraction(c) * S for e, c in pl} for pl in cert['cX']]
    dY = [{code(e): Fraction(c) * S for e, c in pl} for pl in cert['dY']]
    for pl in cX + dY:
        for v in pl.values():
            assert v.denominator == 1
    # quadrics as polys in X (indices 0..8) and Y (9..17)
    def qpoly(q, off):
        d = {}
        for mm, c in q:
            e = [0] * 18
            e[off + mm[0]] += 1
            e[off + mm[1]] += 1
            d[code(e)] = d.get(code(e), 0) + c
        return d
    QX = [qpoly(q, 0) for q in quads]
    QY = [qpoly(q, 9) for q in quads]
    out = ['/-! GENERATED by scripts/abvar_spike/gen_lean_proto.py (ABVAR A0b prototype).',
           f'Membership certificate for law m = {m}, quadric j = {j}; scale S = {S}. -/',
           '', 'namespace AbvarProto', '', 'set_option maxRecDepth 100000', '',
           'abbrev Poly := List (Nat × Int)', '',
           '/-- merge-add of two polys sorted by monomial code (fuel = total length + 1). -/',
           'def mergeAdd : Nat → Poly → Poly → Poly',
           '  | 0, p, q => p ++ q',
           '  | _+1, [], q => q',
           '  | _+1, p, [] => p',
           '  | f+1, (m, a) :: p, (n, b) :: q =>',
           '    if m < n then (m, a) :: mergeAdd f p ((n, b) :: q)',
           '    else if n < m then (n, b) :: mergeAdd f ((m, a) :: p) q',
           '    else if a + b = 0 then mergeAdd f p q else (m, a + b) :: mergeAdd f p q',
           '', 'def add (p q : Poly) : Poly := mergeAdd (p.length + q.length + 1) p q', '',
           'def scaleShift (m : Nat) (c : Int) : Poly → Poly',
           '  | [] => []',
           '  | (n, b) :: p => (n + m, c * b) :: scaleShift m c p', '',
           '/-- one round of pairwise merging. -/',
           'def pairUp : List Poly → List Poly',
           '  | p :: q :: rest => add p q :: pairUp rest',
           '  | l => l', '',
           'def sumAux : Nat → List Poly → Poly',
           '  | _, [] => []',
           '  | _, [p] => p',
           '  | 0, l => l.foldl add []',
           '  | f+1, l => sumAux f (pairUp l)', '',
           'def sumPolys (l : List Poly) : Poly := sumAux 64 l', '']
    if variant == 'tree':
        out.append('def mul (p q : Poly) : Poly := sumPolys (p.map fun t => scaleShift t.1 t.2 q)')
    else:
        out.append('def mul (p q : Poly) : Poly := p.foldl (fun acc t => add acc (scaleShift t.1 t.2 q)) []')
    out.append('def neg (p : Poly) : Poly := p.map fun t => (t.1, -t.2)')
    out.append('')
    for k in range(9):
        lean_list(f'A{k}', sorted((c, int(v)) for c, v in A[k].items()), out)
    for i in range(len(quads)):
        lean_list(f'QX{i}', sorted((c, int(v)) for c, v in QX[i].items()), out)
        lean_list(f'QY{i}', sorted((c, int(v)) for c, v in QY[i].items()), out)
        lean_list(f'cX{i}', sorted((c, int(v)) for c, v in cX[i].items()), out)
        lean_list(f'dY{i}', sorted((c, int(v)) for c, v in dY[i].items()), out)
    # lhs: Q_j(A) = sum c * A_a * A_b
    lhs_terms = []
    for mm, c in quads[j]:
        lhs_terms.append(f'scaleShift 0 ({c} * {S // 1024}) (mul A{mm[0]} A{mm[1]})')
    out.append('def lhs : Poly := sumPolys [' + ', '.join(lhs_terms) + ']')
    rhs_terms = [f'mul cX{i} QX{i}' for i in range(len(quads))] + [f'mul dY{i} QY{i}' for i in range(len(quads))]
    out.append('def rhs : Poly := sumPolys [' + ', '.join(rhs_terms) + ']')
    out.append('def check : Bool := (add lhs (neg rhs)).isEmpty')
    out.append('')
    out.append(f'theorem cert_m{m}_j{j} : check = true := by decide +kernel')
    out.append('')
    out.append('end AbvarProto')
    path = os.path.join(outdir, 'AbvarProto', f'Cert_m{m}_j{j}.lean')
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(out) + '\n')
    print('wrote', path, 'S =', S)


if __name__ == '__main__':
    main()
