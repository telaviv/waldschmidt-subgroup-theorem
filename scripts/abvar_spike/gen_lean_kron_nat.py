"""A0b step 8c (Nat-only, sign-split variant of gen_lean_kron.py).
A0b step 8b: Lean prototype of ONE law identity checked in the kernel by big-integer arithmetic
("normal form + two-level Kronecker" checker), instead of sparse-list polynomial arithmetic.

Claim checked: NF(S * Q_j(A^{(m)}(X, Y))) = 0 in (S/I)_4 (x) (S/I)_4, where NF is the degree-4 normal-form map
modulo (Q)_4 = I_4 (144 standard monomials, entries scaled by delta = 7680 to integers).  Computation in the kernel:
    O = sum_{quadric terms c X_a X_b} c * sum_mu KX(mu) * sum_{(alpha,alpha') : alpha+alpha'=mu} Yprod(A_a[alpha], A_b[alpha'])
    Yprod(p, q) = sum_{(beta,c) in p, (beta',c') in q} c c' KY(beta + beta')
    KY(nu) = sum_t N[nu,t] 2^{b t},   KX(mu) = sum_s N[mu,s] 2^{W s},   W = 144 b + 64
O = 0 with every final digit bounded by 2^{b-1} (checked here in Python via the L1 bound; in Lean this would be one
more kernel sum with absolute values) implies NF(...) = 0.  For the timing prototype the soundness lemmas are not
written; only the kernel computation is timed.

Usage: python gen_lean_kron.py m j OUTDIR        writes OUTDIR/AbvarProto/Kron_m<m>_j<j>.lean
"""
import itertools
import json
import os
import sys
from fractions import Fraction
from math import lcm
import flint
from cert_sizes import Lifter, monos4

WT = [0, 6, 4, 2, 9, 7, 5, 3, 8]


def code(m):   # m: tuple of variable indices (multiset), 9 vars, base 8
    e = [0] * 9
    for i in m:
        e[i] += 1
    return sum(x * 8 ** i for i, x in enumerate(e))


def main():
    mode = sys.argv[1]
    if mode == 'v2':   # rank-one identity  A_k^(m) A_0^(0) - A_k^(0) A_0^(m)
        kk, mm, outdir = int(sys.argv[2]), int(sys.argv[3]), sys.argv[4]
        prods = [(1, (kk, mm), (0, 0)), (-1, (kk, 0), (0, mm))]
        tag = f'V2_k{kk}_m{mm}'
    else:
        m, j, outdir = int(sys.argv[1]), int(sys.argv[2]), sys.argv[3]
        tag = f'Kron_m{m}_j{j}'
    quads_raw = json.load(open('ideal.json'))['quadrics']
    quads = [{tuple(mm): c for mm, c in q} for q in quads_raw]
    lq = json.load(open('laws_Q.json'))
    std2 = [tuple(s) for s in lq['std']]
    sidx = {s: i for i, s in enumerate(std2)}
    # NF4 scaled
    L = Lifter(quads)
    delta = 7680
    NF = {}
    for c, mono in enumerate(monos4):
        nf, _ = L.lift({c: flint.fmpq(1)})
        row = {}
        for col, v in nf.items():
            w = v * delta
            assert w.q == 1
            row[col] = int(w.p)
        NF[mono] = row
    stdcols = sorted({col for r in NF.values() for col in r})
    assert len(stdcols) == 144
    tpos = {col: t for t, col in enumerate(stdcols)}
    # laws: A_(k,m) as list over alpha (std2 index) of list of (beta code, coeff*32)
    if mode != 'v2':
        prods = [(cq, (qm[0], m), (qm[1], m)) for qm, cq in quads[j].items()]
    need = sorted({p[1] for p in prods} | {p[2] for p in prods})
    A = {}
    for (k, m_) in need:
        rows = [[] for _ in std2]
        for e, c in lq['laws'][f'{k},{m_}']:
            al = tuple(i for i in range(9) for _ in range(e[i]))
            be = tuple(i for i in range(9) for _ in range(e[9 + i]))
            v = Fraction(c) * 32
            assert v.denominator == 1
            rows[sidx[al]].append((be, int(v)))
        A[(k, m_)] = rows
    # decompositions
    dec = {}
    for i, a in enumerate(std2):
        for i2, a2 in enumerate(std2):
            mu = tuple(sorted(a + a2))
            dec.setdefault(mu, []).append((i, i2))
    # ---- Python simulation (exact): digits v[s][t]
    V = {}
    Vabs = {}
    for cq, a, b_ in prods:
        for mu, ds in dec.items():
            for (i, i2) in ds:
                for be, c1 in A[a][i]:
                    for be2, c2 in A[b_][i2]:
                        nu = tuple(sorted(be + be2))
                        coef = cq * c1 * c2
                        for s, x in NF[mu].items():
                            for t, y in NF[nu].items():
                                key = (tpos[s], tpos[t])
                                V[key] = V.get(key, 0) + coef * x * y
                                Vabs[key] = Vabs.get(key, 0) + abs(coef * x * y)
    assert all(v == 0 for v in V.values()), 'identity fails'
    L1 = max(Vabs.values())
    bbits = L1.bit_length() + 2
    W = 144 * bbits + 64
    print(f'Python simulation: NF(Q_j(A)) = 0 OK; max digit L1 bound {L1.bit_length()} bits -> b = {bbits}, W = {W}')

    def nat_pair(terms, width):
        """terms -> (P, N) Lean Nat expressions with value P - N."""
        pp, nn = [], []
        for slot, v in terms:
            sh = width * slot
            (pp if v > 0 else nn).append(f'({abs(v)} <<< {sh})')
        return (' + '.join(pp) if pp else '0'), (' + '.join(nn) if nn else '0')

    out = ['/-! GENERATED by scripts/abvar_spike/gen_lean_kron.py (ABVAR A0b prototype, timing only). -/',
           '', 'namespace AbvarKron', '', 'set_option maxRecDepth 1000000', '']
    # KY and KX constants
    monos_needed = sorted(set(dec.keys()) | {tuple(sorted(x + y)) for x in std2 for y in std2})
    for idx, mono in enumerate(monos4):
        if mono not in monos_needed:
            continue
        row = sorted((tpos[s], v) for s, v in NF[mono].items())
        p_, n_ = nat_pair(row, bbits)
        out.append(f'def ky{idx} : Nat × Nat := ({p_}, {n_})')
        p_, n_ = nat_pair(row, W)
        out.append(f'def kx{idx} : Nat × Nat := ({p_}, {n_})')
    # decision trees on codes
    entries = sorted((code(mono), monos4.index(mono)) for mono in monos_needed)

    def tree(lo, hi, pref):
        if hi - lo == 1:
            return f'(.leaf {pref}{entries[lo][1]})'
        mid = (lo + hi) // 2
        return f'(.node {entries[mid][0]} {tree(lo, mid, pref)} {tree(mid, hi, pref)})'
    out.append('inductive T where')
    out.append('  | leaf (v : Nat × Nat)')
    out.append('  | node (k : Nat) (l r : T)')
    out.append('def T.find : T → Nat → Nat × Nat')
    out.append('  | .leaf v, _ => v')
    out.append('  | .node k l r, c => if c < k then l.find c else r.find c')
    out.append('def kyT : T := ' + tree(0, len(entries), 'ky'))
    out.append('def kxT : T := ' + tree(0, len(entries), 'kx'))
    out.append('def KY (c : Nat) : Nat × Nat := kyT.find c')
    out.append('def KX (c : Nat) : Nat × Nat := kxT.find c')
    out.append('')
    for (k, m_) in need:
        rows = ', '.join('[' + ', '.join(f'({code(be)}, {abs(c)}, {"true" if c < 0 else "false"})' for be, c in r) + ']' for r in A[(k, m_)])
        out.append(f'def A{k}_{m_} : List (List (Nat × Nat × Bool)) := [{rows}]')
    decl = ', '.join(f'({code(mu)}, [' + ', '.join(f'({i}, {i2})' for i, i2 in ds) + '])' for mu, ds in dec.items())
    out.append(f'def dec : List (Nat × List (Nat × Nat)) := [{decl}]')
    out += ['',
            '/-- signed accumulation: a pair (P, N) stands for P - N. -/',
            'def addS (acc : Nat × Nat) (c : Nat) (neg : Bool) (v : Nat × Nat) : Nat × Nat :=',
            '  if neg then (acc.1 + c * v.2, acc.2 + c * v.1) else (acc.1 + c * v.1, acc.2 + c * v.2)',
            '',
            'def yprod (p q : List (Nat × Nat × Bool)) (acc : Nat × Nat) : Nat × Nat :=',
            '  p.foldl (fun acc t => q.foldl (fun acc2 u =>',
            '    addS acc2 (t.2.1 * u.2.1) (t.2.2 != u.2.2) (KY (t.1 + u.1))) acc) acc',
            '',
            'def mulS (x y : Nat × Nat) : Nat × Nat := (x.1 * y.1 + x.2 * y.2, x.1 * y.2 + x.2 * y.1)',
            '',
            'def prodNF (c : Nat) (neg : Bool) (Aa Ab : List (List (Nat × Nat × Bool))) (acc : Nat × Nat) : Nat × Nat :=',
            '  dec.foldl (fun acc d => addS acc c neg (mulS (KX d.1) (d.2.foldl',
            '    (fun a2 ii => yprod (Aa.getD ii.1 []) (Ab.getD ii.2 []) a2) (0, 0)))) acc',
            '']
    chain = '(0, 0)'
    for cq, a, b_ in prods:
        chain = f'(prodNF {abs(cq)} {"true" if cq < 0 else "false"} A{a[0]}_{a[1]} A{b_[0]}_{b_[1]} {chain})'
    out.append('def O : Nat × Nat := ' + chain)
    out.append('')
    out.append(f'theorem {tag.lower()} : O.1 = O.2 := by decide +kernel')
    out.append('')
    out.append('end AbvarKron')
    path = os.path.join(outdir, 'AbvarProto', f'{tag}_nat.lean')
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(out) + '\n')
    print('wrote', path, os.path.getsize(path), 'bytes')


if __name__ == '__main__':
    main()
