def red_cof(E):
    """E = c * (a^5 - 2) exactly (as polynomials in a, other symbols as parameters); return c"""
    qt, r = sp.div(sp.Poly(sp.expand(E), a), sp.Poly(MIN, a))
    assert r.is_zero, r
    return sp.expand(qt.as_expr())


def ls(e):
    """sympy expr -> Lean string, with a -> α, d -> δ, x1/x2/y1/y2 names kept"""
    s = sp.sstr(sp.expand(e))
    s = s.replace('**', '^')
    s = s.replace('a', 'α').replace('d', 'δ')
    return s


grantA = lambda m: [1, m[2] ** 2 / 4 - m[0] ** 3 + m[0] * m[1], -m[1], m[0],
                    -2 * m[3] * m[0] ** 2 + m[3] * m[1] - m[2] ** 3 / 4 + m[2] * m[0] ** 3 - 3 * m[2] * m[0] * m[1],
                    -m[3] * m[0] - m[2] * m[1], m[3], m[2], m[3] * m[2] / 2 + 2 * m[0] ** 2 * m[1]]
