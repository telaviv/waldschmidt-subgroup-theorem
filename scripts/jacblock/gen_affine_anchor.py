# ------------------------------------------------------------------ Affine
X0 = X[0]
h = lambda c: q(Fraction(c))
p0, p1, p2, p3 = X[3], -X[2], X[7], X[6]
grant = [None,
         q(Fraction(1, 4)) * p2 ** 2 - p0 ** 3 + p0 * p1,
         -p1, p0,
         -2 * p3 * p0 ** 2 + p3 * p1 - q(Fraction(1, 4)) * p2 ** 3 + p2 * p0 ** 3 - 3 * p2 * p0 * p1,
         -p3 * p0 - p2 * p1, p3, p2,
         q(Fraction(1, 2)) * p3 * p2 + 2 * p0 ** 2 * p1]
R1 = -2 * p3 * p2 - p2 ** 2 * p0 + 4 * p0 ** 4 - 12 * p0 ** 2 * p1 + 4 * p1 ** 2
R0 = -p3 ** 2 + p2 ** 2 * p1 - 4 * p0 ** 3 * p1 + 8 * p0 * p1 ** 2 + 1


def homog(T):
    d = deg(T)
    out = ZERO
    for e, c in T.to_dict().items():
        out += c * mono(e) * X0 ** (d - sum(e))
    return out


def aff_cert(T):
    Th = homog(T)
    cof = member(Th, GENS)
    assert cof is not None
    rest = T
    for c, g in zip(cof, GENS):
        rest -= c * g
    b, r = divmod(rest, X0 - 1)
    assert r == 0
    return cof, b


def lp(p):
    return lean_poly(p, 'X')


def lc_terms(cof, b, hb='hX0'):
    t = [f'({lp(c)}) * h{j}' for j, c in enumerate(cof) if c != 0]
    if b != 0:
        t.append(f'({lp(b)}) * {hb}')
    return ' + '.join(t) if t else '0'


