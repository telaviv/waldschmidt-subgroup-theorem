"""Generate LSG/JacBlock/Exit.lean (UNTRUSTED generator; Lean re-checks everything by `ring`/`linear_combination`).

Exit words D_v^k X_0 for the chart-4/8 fields (A1's W4C = W4n/4, W8C = W8n/4), k = 1, 2, 3, as explicit polynomials
in (v, X):  w_k(v, X) = sum_{n0} v0^{n0} v1^{k-n0} S_{k,n0}(X), S = sum of the D-words with n0 letters D_0.
Exit certificates (exact over Q, X_0 = 0 allowed as a generator):
  chart 4:  X_4^4 = sum a_i G_i + b X_0 + c w_3(e_0)
  chart 8:  X_8^5 = sum a_i G_i + b X_0 + c_1 w_1(e_0) + c_2 w_2(e_0) + c_3 w_3(e_0) + c_4 w_3(e_1)
Usage: python gen_exit.py
"""
from jb_common import *

OUT = os.path.join(ROOT, 'LSG', 'JacBlock', 'Exit.lean')


def lp(p):
    return lean_poly(p, 'X')


def sym_words(F):
    words = {(): X[0]}
    for k in range(1, 4):
        for w in itertools.product((0, 1), repeat=k):
            words[w] = D(F, w[0], words[w[1:]])
    S = {}
    for k in range(1, 4):
        for n0 in range(k + 1):
            S[(k, n0)] = sum((words[w] for w in itertools.product((0, 1), repeat=k) if w.count(0) == n0), ZERO)
    return S


def vmono(n0, n1):
    f = []
    if n0:
        f.append('v 0' if n0 == 1 else f'v 0 ^ {n0}')
    if n1:
        f.append('v 1' if n1 == 1 else f'v 1 ^ {n1}')
    return ' * '.join(f)


def word_lean(S, k):
    parts = []
    for n0 in range(k, -1, -1):
        p = S[(k, n0)]
        if p != 0:
            parts.append(f'{vmono(n0, k - n0)} * ({lp(p)})')
    return ' +\n    '.join(parts) if parts else '0'


def words_dir(F, v):
    w = [X[0]]
    for _ in range(3):
        w.append(Dv(F, v, w[-1]))
    return w


L = ['/-', 'Copyright (c) 2026. All rights reserved.', 'Released under Apache 2.0 license.', '-/',
     'import LSG.JacBlock.Gens', 'import LSG.JacAn4.SurjFacts', '',
     '/-! GENERATED by scripts/jacblock/gen_exit.py — do not edit.', '',
     '# Flow exit at the boundary `X₀ = 0` (A4.1b, S-c)', '',
     '* `w4_k v`, `w8_k v` (`k = 1, 2, 3`): explicit polynomials with **`exitWord_W4G_k`**, **`exitWord_W8G_k`**:',
     '  `exitWord W v k = w_k v` (so the exit words are polynomial, hence differentiable, for `k ≤ 3`).',
     '* **`exit4G`**: on the model, `X₀ = 0`, `X₄ ≠ 0` ⇒ `exitWord W4G e₀ 3 X ≠ 0`; certificate',
     '  `X₄⁴ ∈ I_A + (X₀, D₀³X₀)`.',
     '* **`exit8G`**: on the model, `X₀ = 0`, `X₈ ≠ 0` ⇒ some `exitWord W8G v k X ≠ 0` with `v ∈ {e₀, e₁}`,',
     '  `1 ≤ k ≤ 3`; certificate `X₈⁵ ∈ I_A + (X₀, D₀X₀, D₀²X₀, D₀³X₀, D₁³X₀)`.',
     '-/', '', 'noncomputable section', '', 'namespace LSG.JacBlock', '',
     'open LSG.JacAn LSG.Jac Finset', '']

for cname, F, c, N, dirs in (('4', W4, 4, 4, [(1, 0)]), ('8', W8, 8, 5, [(1, 0), (0, 1)])):
    S = sym_words(F)
    Wg = f'W{cname}G'
    for k in (1, 2, 3):
        L += [f'/-- The exit word `D_v^{k} X₀` of the chart-{cname} flow. -/',
              f'def w{cname}_{k} (v : Fin 2 → ℂ) : P9 → ℂ := fun X =>', '    ' + word_lean(S, k), '']
    L += [f'lemma exitWord_{Wg}_1 (v : Fin 2 → ℂ) : exitWord {Wg} v 1 = w{cname}_1 v := by',
          '  funext X',
          '  simp only [exitWord, Function.iterate_one, derivW]',
          '  simp (disch := fun_prop) [fderiv_apply]',
          f'  simp [w{cname}_1, {Wg}, W{cname}n]',
          '  ring', '']
    for k in (2, 3):
        L += [f'lemma exitWord_{Wg}_{k} (v : Fin 2 → ℂ) : exitWord {Wg} v {k} = w{cname}_{k} v := by',
              f'  have h : exitWord {Wg} v {k} = derivW {Wg} v (exitWord {Wg} v {k - 1}) :=',
              '    Function.iterate_succ_apply\' _ _ _',
              f'  rw [h, exitWord_{Wg}_{k - 1}]',
              '  funext X',
              '  simp only [derivW]',
              f'  unfold w{cname}_{k - 1}',
              f'  simp (disch := fun_prop) [fderiv_fun_sub, fderiv_fun_add, fderiv_fun_mul,',
              '    fderiv_fun_pow, fderiv_apply, fderiv_fun_neg]',
              f'  simp [w{cname}_{k}, {Wg}, W{cname}n]',
              '  ring', '']
    # certificate
    gens = GENS + [X[0]]
    labels = [('G', i) for i in range(12)] + [('X0',)]
    for v in dirs:
        ws = words_dir(F, v)
        for k in (1, 2, 3):
            gens.append(ws[k])
            labels.append(('w', v, k))
    cof = member(X[c] ** N, gens, weighted=True)
    assert cof is not None
    used = [(lab, cc) for lab, cc in zip(labels, cof) if cc != 0]
    print('chart', cname, 'used', [(lab, nterms(cc)) for lab, cc in used])
    hyps = []
    terms = []
    for lab, cc in used:
        if lab[0] == 'G':
            terms.append(f'({lp(cc)}) * h{lab[1]}')
        elif lab[0] == 'X0':
            terms.append(f'({lp(cc)}) * hX0')
        else:
            v, k = lab[1], lab[2]
            nm = f'hw_{v[0]}{v[1]}_{k}'
            terms.append(f'({lp(cc)}) * {nm}')
            hyps.append((nm, v, k))
    vlean = {(1, 0): '![1, 0]', (0, 1): '![0, 1]'}
    L += [f'/-- **Flow exit in chart {cname}.** -/',
          f'theorem exit{cname}G (X : P9) (hX : OnQ X) (hX0 : X 0 = 0) (hc : X {c} ≠ 0) :',
          f'    ∃ v : Fin 2 → ℂ, ∃ k : ℕ, 1 ≤ k ∧ k ≤ 3 ∧ exitWord {Wg} v k X ≠ 0 := by',
          '  by_contra hne',
          '  push_neg at hne',
          '  have hg := (onQ_iff_gens X).mp hX',
          '  have h0 := hg 0; have h1 := hg 1; have h2 := hg 2; have h3 := hg 3; have h4 := hg 4; have h5 := hg 5',
          '  have h6 := hg 6; have h7 := hg 7; have h8 := hg 8; have h9 := hg 9; have h10 := hg 10',
          '  have h11 := hg 11',
          '  simp only [gensA, Matrix.cons_val, Fin.isValue] at h0 h1 h2 h3 h4 h5 h6 h7 h8 h9 h10 h11']
    for nm, v, k in hyps:
        sw = S[(k, k)] if v == (1, 0) else S[(k, 0)]
        L += [f'  have {nm} : {lp(sw)} = 0 := by',
              f'    have e := hne {vlean[v]} {k} (by norm_num) (by norm_num)',
              f'    rw [exitWord_{Wg}_{k}] at e',
              '    refine Eq.trans ?_ e',
              f'    simp only [w{cname}_{k}, Matrix.cons_val_zero, Matrix.cons_val_one, Matrix.head_cons]',
              '    ring']
    L += [f'  have key : X {c} ^ {N} = 0 := by',
          '    linear_combination ' + ' + '.join(terms),
          '  exact hc (pow_eq_zero_iff (by norm_num) |>.mp key)', '']

for cname in ('4', '8'):
    Wg = f'W{cname}G'
    L += [f'/-- The exit words of order `≤ 3` are polynomial, hence differentiable. -/',
          f'theorem exitWord_{Wg}_differentiable (v : Fin 2 → ℂ) {{k : ℕ}} (hk : k ≤ 3) :',
          f'    Differentiable ℂ (exitWord {Wg} v k) := by',
          '  interval_cases k',
          '  · show Differentiable ℂ fun X : P9 => X 0',
          '    fun_prop',
          ] + [f'  · rw [exitWord_{Wg}_{k}]; unfold w{cname}_{k}; fun_prop' for k in (1, 2, 3)] + ['']
L += ['end LSG.JacBlock', '']
open(OUT, 'w', encoding='utf-8').write('\n'.join(L))
print('wrote', OUT, len(L), 'lines')
