H = HDR + ['import LSG.JacBlock.GensMv', '',
           '/-! GENERATED by scripts/jacblock/gen_hilb.py — do not edit.', '',
           '# B6: the Hilbert certificate of the A-block (Gröbner-free)', '',
           'With `y = (X₀, X₄, X₈)` and `J = (gens) + (y)`: `X_v^{e_v} ∈ J` for `e = (1,3,3,3,1,4,3,3,1)` (explicit',
           'cofactors, checked through `MvPolynomial.funext` and `ring`). Since `Σ (e_v − 1) = 13`, every monomial of',
           'degree `14` is divisible by some `X_v^{e_v}`, so **`hilbA`**: every homogeneous polynomial of degree 14 lies in',
           '`J`. (STAGE_A4 §3.2 has `n₀ = 4` with 41 certificates; `n₀ = 14` needs only these 6 and changes only the',
           'constant of the Hilbert bound.)', '-/', '',
           'noncomputable section', '', 'namespace LSG.JacBlock', '', 'open MvPolynomial', '',
           '/-- The Noether triple `y = (X₀, X₄, X₈)`. -/',
           'def yA : Fin 3 → Fin 9 := ![0, 4, 8]', '',
           '/-- `J = (gens) + (y)`. -/',
           'def JA : Ideal (MvPolynomial (Fin 9) ℂ) :=',
           '  Ideal.span {Q | Q ∈ gensMv} ⊔ Ideal.span (Set.range fun a => (X (yA a) : MvPolynomial (Fin 9) ℂ))', '',
           '/-- The exponents `e_v`. -/',
           'def eA : Fin 9 → ℕ := ![' + ', '.join(map(str, EV)) + ']', '',
           'lemma gen_mem {Q : MvPolynomial (Fin 9) ℂ} (h : Q ∈ gensMv) : Q ∈ JA :=',
           '  Ideal.mem_sup_left (Ideal.subset_span h)', '',
           'lemma y_mem (a : Fin 3) : (X (yA a) : MvPolynomial (Fin 9) ℂ) ∈ JA :=',
           '  Ideal.mem_sup_right (Ideal.subset_span ⟨a, rfl⟩)', '']
yidx = {0: 0, 4: 1, 8: 2}
for v in range(9):
    if v in yidx:
        H += [f'lemma pow_mem_{v} : (X {v} : MvPolynomial (Fin 9) ℂ) ^ eA {v} ∈ JA := by',
              f'  simpa [eA, yA] using y_mem {yidx[v]}', '']
        continue
    gens = GENS + [X[0], X[4], X[8]]
    cof = member(X[v] ** EV[v], gens)
    assert cof is not None
    parts = []
    for i, c in enumerate(cof[:12]):
        if c != 0:
            parts.append(f'Ideal.mul_mem_left _ ({lmv(c)}) (gen_mem (by simp [gensMv]) : {NAMES_G[i]} ∈ JA)')
    for a, c in enumerate(cof[12:]):
        if c != 0:
            parts.append(f'Ideal.mul_mem_left _ ({lmv(c)}) (by simpa [yA] using y_mem {a})')
    expr = ' + '.join(f'({lmv(c)}) * {NAMES_G[i]}' for i, c in enumerate(cof[:12]) if c != 0)
    expr2 = ' + '.join(f'({lmv(c)}) * X {[0, 4, 8][a]}' for a, c in enumerate(cof[12:]) if c != 0)
    full = ' + '.join(x for x in (expr, expr2) if x)
    # membership term: nested Ideal.add_mem
    mem = parts[0]
    for p_ in parts[1:]:
        mem = f'Ideal.add_mem _ ({mem}) ({p_})'
    H += [f'lemma pow_mem_{v} : (X {v} : MvPolynomial (Fin 9) ℂ) ^ eA {v} ∈ JA := by',
          f'  have h : (X {v} : MvPolynomial (Fin 9) ℂ) ^ eA {v} = {full} := by',
          '    apply MvPolynomial.funext; intro x',
          '    simp [eA, ' + ', '.join(NAMES_G) + ']',
          '    ring',
          '  rw [h]',
          f'  exact {mem}', '']
H += ['lemma pow_mem (v : Fin 9) : (X v : MvPolynomial (Fin 9) ℂ) ^ eA v ∈ JA := by',
      '  fin_cases v'] + [f'  · exact pow_mem_{v}' for v in range(9)] + ['',
      'lemma monomial_mem_of_le (s : Fin 9 →₀ ℕ) (v : Fin 9) (hv : eA v ≤ s v) : monomial s (1 : ℂ) ∈ JA := by',
      '  have hle : Finsupp.single v (eA v) ≤ s := by',
      '    intro i; by_cases h : i = v',
      '    · subst h; simpa using hv',
      '    · simp [Finsupp.single_apply, Ne.symm h]',
      '  have : monomial s (1 : ℂ) = X v ^ eA v * monomial (s - Finsupp.single v (eA v)) 1 := by',
      '    rw [X_pow_eq_monomial, monomial_mul, one_mul, add_tsub_cancel_of_le hle]',
      '  rw [this]; exact Ideal.mul_mem_right _ _ (pow_mem v)', '',
      'lemma monomial_mem (s : Fin 9 →₀ ℕ) (hs : 13 < ∑ i, s i) : monomial s (1 : ℂ) ∈ JA := by',
      '  by_contra hne',
      '  have hlt : ∀ v, s v + 1 ≤ eA v := fun v => by',
      '    by_contra h; push_neg at h; exact hne (monomial_mem_of_le s v (by omega))',
      '  have : ∑ i, s i ≤ 13 := by',
      '    have h2 := Finset.sum_le_sum (fun i (_ : i ∈ Finset.univ) => hlt i)',
      '    simp only [Finset.sum_add_distrib, Finset.sum_const, Finset.card_univ, Fintype.card_fin,',
      '      smul_eq_mul, mul_one] at h2',
      '    have h3 : ∑ i, eA i = 22 := by simp [eA, Fin.sum_univ_succ]',
      '    omega',
      '  omega', '',
      '/-- **B6, the Hilbert certificate**: every homogeneous polynomial of degree 14 lies in `(gens) + (X₀, X₄, X₈)`. -/',
      'theorem hilbA (M : MvPolynomial (Fin 9) ℂ) (hM : M.IsHomogeneous 14) : M ∈ JA := by',
      '  rw [M.as_sum]',
      '  refine Ideal.sum_mem _ fun s hs => ?_',
      '  have hdeg : ∑ i, s i = 14 := by',
      '    have := hM (mem_support_iff.mp hs)',
      '    simpa [Finsupp.weight_apply, Finsupp.sum_fintype] using this',
      '  have : monomial s (M.coeff s) = C (M.coeff s) * monomial s 1 := by',
      '    rw [C_mul_monomial, mul_one]',
      '  rw [this]',
      '  exact Ideal.mul_mem_left _ _ (monomial_mem s (by omega))', '',
      'end LSG.JacBlock', '']
open(os.path.join(ROOT, 'LSG', 'JacBlock', 'Hilb.lean'), 'w', encoding='utf-8').write('\n'.join(H))
