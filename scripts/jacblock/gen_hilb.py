"""Generate LSG/JacBlock/GensMv.lean and LSG/JacBlock/Hilb.lean (UNTRUSTED generator; Lean re-checks every identity).

GensMv: the 12 generators as MvPolynomials (`gensMv`), with eval = gensA.
Hilb (B6): with y = (X0, X4, X8) and e = (1,3,3,3,1,4,3,3,1):  X_v^{e_v} in J = (gens) + (y) for every v
(certificates by exact linear algebra, b6_try.py), hence (pigeonhole, sum (e_v - 1) = 13) every monomial of
degree 14 lies in J:  hilb_deg = 14.
Usage: python gen_hilb.py
"""
from jb_common import *

EV = [1, 3, 3, 3, 1, 4, 3, 3, 1]
NAMES_G = [f'gQ{i}' for i in range(9)] + [f'gC{j}' for j in range(3)]
HDR = ['/-', 'Copyright (c) 2026. All rights reserved.', 'Released under Apache 2.0 license.', '-/']


def lmv(p):
    """MvPolynomial (Fin 9) ℂ expression: sum of C c * X i ^ e ..."""
    if p == 0:
        return '0'
    terms = []
    for e, c in sorted(p.to_dict().items(), reverse=True):
        c = Fraction(int(c.p), int(c.q))
        fac = [f'C ({c.numerator} / {c.denominator} : ℂ)' if c.denominator != 1 else f'C ({c.numerator} : ℂ)']
        for i in range(9):
            if e[i] == 1:
                fac.append(f'X {i}')
            elif e[i] > 1:
                fac.append(f'X {i} ^ {e[i]}')
        terms.append(' * '.join(fac))
    return ' + '.join(terms)


