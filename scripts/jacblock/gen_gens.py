"""Generate LSG/JacBlock/Gens.lean (UNTRUSTED generator; every identity is re-checked by `ring`/`linear_combination`).

Content: the 12 generators of I_A (9 quadrics + 3 cubics, jb_common.CUB), their formal partials, the cubic
memberships X_k C_j in (Q)_4 (27 identities), and the tangency cofactors of the chart-4/8 flows:
    sum_l d_l G_i (X) * W^{[c]}_{j,l}(X) = sum_k tanC_{c,j,i,k}(X) G_k(X)      (polynomial identities).
Usage: python gen_gens.py
"""
from jb_common import *

OUT = os.path.join(ROOT, 'LSG', 'JacBlock', 'Gens.lean')


def lp(p):
    return lean_poly(p, 'X')


L = []
L += ['/-', 'Copyright (c) 2026. All rights reserved.', 'Released under Apache 2.0 license.', '-/',
      'import LSG.Jac.WTables', '',
      '/-! GENERATED by scripts/jacblock/gen_gens.py — do not edit.', '',
      '# Generators of the ideal of `A` and tangency of the chart-4/8 flows (A4.1b, S-c)', '',
      '* `gensA i` (`i < 9`: the quadrics `quad`; `i = 9, 10, 11`: three cubics spanning `I₃/(Q)₃`, found by',
      '  `scripts/jacblock/find_cubics.py`). **`onQ_iff_gens`**: `OnQ X ↔ ∀ i, gensA i X = 0` (over `ℂ`): each',
      '  `X_k · C_j` lies in `(Q)₄` (27 identities, quadratic cofactors), and some `X_k ≠ 0` unless `X = 0`.',
      '* `dgensA i l` are the formal partials; **`fderiv_gensA`** identifies them with the Fréchet derivative.',
      '* **`gens_tan4`/`gens_tan8`**: `fderiv (gensA i) X (W j X) = Σ_k tanC j i k X · gensA k X` for the chart-4/8',
      '  fields `W4G = W4n/4`, `W8G = W8n/4` (A1\'s `W4C`, `W8C`); polynomial identities, all `X`.',
      '-/', '', 'noncomputable section', '', 'namespace LSG.JacBlock', '',
      'open LSG.JacAn LSG.Jac Finset', '',
      '/-- The chart-4 flow (A1\'s `W4C`). -/',
      'def W4G (j : Fin 2) (X : P9) : P9 := fun i => W4n X j i / 4', '',
      '/-- The chart-8 flow (A1\'s `W8C`). -/',
      'def W8G (j : Fin 2) (X : P9) : P9 := fun i => W8n X j i / 4', '']

# generators
L.append('/-- The 12 generators: 9 quadrics, then 3 cubics. -/')
L.append('def gensA : Fin 12 → P9 → ℂ := ![')
L.append(',\n'.join(f'  fun X => {lp(g)}' for g in GENS) + ']')
L.append('')
# partials
L.append('/-- Formal partials `∂ gensA i / ∂ X_l`. -/')
L.append('def dgensA : Fin 12 → Fin 9 → P9 → ℂ := ![')
L.append(',\n'.join('  ![' + ', '.join(f'fun X => {lp(g.derivative(l))}' if g.derivative(l) != 0 else 'fun _ => 0'
                                      for l in range(9)) + ']' for g in GENS) + ']')
L.append('')
L += ['theorem gensA_diff (i : Fin 12) : Differentiable ℂ (gensA i) := by',
      '  fin_cases i <;> simp only [gensA] <;> simp <;> fun_prop', '',
      ]
for i in range(12):
    L += [f'lemma fderiv_gensA_{i} (X v : P9) : fderiv ℂ (gensA {i}) X v = ∑ l : Fin 9, dgensA {i} l X * v l := by',
          '  simp (disch := fun_prop) [gensA, fderiv_fun_sub, fderiv_fun_add, fderiv_fun_mul, fderiv_fun_pow,',
          '    fderiv_apply, fderiv_fun_neg]',
          '  simp [Fin.sum_univ_succ, dgensA]; ring', '']
L += ['theorem fderiv_gensA (i : Fin 12) (X v : P9) : fderiv ℂ (gensA i) X v = ∑ l : Fin 9, dgensA i l X * v l := by',
      '  fin_cases i',
      ] + [f'  · exact fderiv_gensA_{i} X v' for i in range(12)] + ['']

# cubic memberships
HYP = ['(h0 : quad X 0 = 0) (h1 : quad X 1 = 0) (h2 : quad X 2 = 0)',
       '    (h3 : quad X 3 = 0) (h4 : quad X 4 = 0) (h5 : quad X 5 = 0) (h6 : quad X 6 = 0) (h7 : quad X 7 = 0)',
       '    (h8 : quad X 8 = 0)']
for j, C in enumerate(CUB):
    for k in range(9):
        cof = member(X[k] * C, Q)
        assert cof is not None
        terms = ' + '.join(f'({lp(c)}) * h{i}' for i, c in enumerate(cof) if c != 0)
        L += [f'lemma cubMul_{j}_{k} (X : P9) ' + HYP[0], HYP[1], HYP[2] + f' : X {k} * gensA {9 + j} X = 0 := by',
              '  simp only [quad, Matrix.cons_val, Fin.isValue] at h0 h1 h2 h3 h4 h5 h6 h7 h8',
              '  simp only [gensA, Matrix.cons_val, Fin.isValue]',
              f'  linear_combination {terms}', '']
    L += [f'lemma cub_zero_{j} (X : P9) ' + HYP[0], HYP[1], HYP[2] + f' : gensA {9 + j} X = 0 := by',
          f'  have key : ∀ k : Fin 9, X k * gensA {9 + j} X = 0 := by',
          '    intro k; fin_cases k',
          ] + [f'    · exact cubMul_{j}_{k} X h0 h1 h2 h3 h4 h5 h6 h7 h8' for k in range(9)] + [
          '  by_cases h : ∀ k, X k = 0',
          '  · have hX0 : X = 0 := funext h',
          '    subst hX0',
          '    simp [gensA]',
          '  · push_neg at h',
          '    obtain ⟨k, hk⟩ := h',
          '    exact (mul_eq_zero.mp (key k)).resolve_left hk', '']
L += ['/-- **The model is cut out by the 12 generators.** -/',
      'theorem onQ_iff_gens (X : P9) : OnQ X ↔ ∀ i, gensA i X = 0 := by',
      '  rw [onQ_iff]',
      '  constructor',
      '  · intro hX',
      '    have h0 := hX 0; have h1 := hX 1; have h2 := hX 2; have h3 := hX 3; have h4 := hX 4',
      '    have h5 := hX 5; have h6 := hX 6; have h7 := hX 7; have h8 := hX 8',
      '    intro i; fin_cases i',
      ] + [f'    · have h := h{i}; simp only [quad, Matrix.cons_val, Fin.isValue] at h; simp only [gensA, Matrix.cons_val, Fin.isValue, Fin.reduceFinMk]; linear_combination h' for i in range(9)] + [
      f'    · exact cub_zero_{j} X h0 h1 h2 h3 h4 h5 h6 h7 h8' for j in range(3)] + [
      '  · intro h i',
      '    fin_cases i',
      ] + [f'    · have h\' := h {i}; simp only [gensA, Matrix.cons_val, Fin.isValue] at h\'; simp only [quad, Matrix.cons_val, Fin.isValue, Fin.reduceFinMk]; linear_combination h\'' for i in range(9)] + ['']


L += ['end LSG.JacBlock', '']
open(OUT, 'w', encoding='utf-8').write('\n'.join(L))
print('wrote', OUT, len(L), 'lines')

# tangency (one file per chart, to keep elaboration memory down)
for cname, F in (('4', W4), ('8', W8)):
    L = ['/-', 'Copyright (c) 2026. All rights reserved.', 'Released under Apache 2.0 license.', '-/',
         'import LSG.JacBlock.Gens', '',
         '/-! GENERATED by scripts/jacblock/gen_gens.py — do not edit.', '',
         f'# Tangency of the chart-{cname} flow to `V(I_A)`, in ideal form (A4.1b, S-c)', '',
         f'**`gens_tan{cname}`**: `fderiv (gensA i) X (W{cname}G j X) = Σ_k tanC{cname} j i k X · gensA k X` for',
         'all `X` (polynomial identities, checked by `ring`). -/', '', 'noncomputable section', '',
         'namespace LSG.JacBlock', '', 'open LSG.JacAn LSG.Jac Finset', '']
    tab = {}
    for j in range(2):
        for i, G in enumerate(GENS):
            cof = member(D(F, j, G), GENS)
            assert cof is not None
            for k, c in enumerate(cof):
                if c != 0:
                    tab[(j, i, k)] = c
    L.append(f'/-- Tangency cofactors of the chart-{cname} flow. -/')
    L.append(f'def tanC{cname} : Fin 2 → Fin 12 → Fin 12 → P9 → ℂ := ![')
    jl = []
    for j in range(2):
        il = []
        for i in range(12):
            kl = [f'fun X => {lp(tab[(j, i, k)])}' if (j, i, k) in tab else 'fun _ => 0' for k in range(12)]
            il.append('    ![' + ',\n      '.join(kl) + ']')
        jl.append('  ![' + ',\n'.join(il) + ']')
    L.append(',\n'.join(jl) + ']')
    L.append('')
    # the table goes into Tan<c>T.lean, the per-j lemmas into Tan<c>_<j>.lean, the assembly into Tan<c>.lean
    tpath = os.path.join(ROOT, 'LSG', 'JacBlock', f'Tan{cname}T.lean')
    open(tpath, 'w', encoding='utf-8').write('\n'.join(L + ['end LSG.JacBlock', '']))
    hdr = L[:4]
    for j in range(2):
        Lj = hdr + [f'import LSG.JacBlock.Tan{cname}T', '',
                    f'/-! GENERATED by scripts/jacblock/gen_gens.py — chart-{cname} tangency, `j = {j}`. -/', '',
                    'noncomputable section', '', 'namespace LSG.JacBlock', '', 'open LSG.JacAn LSG.Jac Finset', '']
        for i in range(12):
            Lj += [f'lemma tanC{cname}_cont_{j}_{i} (k : Fin 12) : Continuous (tanC{cname} {j} {i} k) := by',
                   f'  fin_cases k <;> simp [tanC{cname}] <;> fun_prop', '',
                   f'lemma gens_tan{cname}_{j}_{i} (X : P9) :',
                   f'    fderiv ℂ (gensA {i}) X (W{cname}G {j} X) = ∑ k, tanC{cname} {j} {i} k X * gensA k X := by',
                   f'  rw [fderiv_gensA_{i}]',
                   f'  simp [Fin.sum_univ_succ, dgensA, tanC{cname}, gensA, W{cname}G, W{cname}n]',
                   '  ring', '']
        Lj += ['end LSG.JacBlock', '']
        open(os.path.join(ROOT, 'LSG', 'JacBlock', f'Tan{cname}_{j}.lean'), 'w', encoding='utf-8').write('\n'.join(Lj))
    L = hdr + [f'import LSG.JacBlock.Tan{cname}_0', f'import LSG.JacBlock.Tan{cname}_1', '',
               '/-! GENERATED by scripts/jacblock/gen_gens.py — do not edit.', '',
               f'# Tangency of the chart-{cname} flow to `V(I_A)`, in ideal form (A4.1b, S-c)', '',
               f'**`gens_tan{cname}`**: `fderiv (gensA i) X (W{cname}G j X) = Σ_k tanC{cname} j i k X · gensA k X` for',
               'all `X` (polynomial identities, checked by `ring`; table in `Tan' + cname + 'T`). -/', '',
               'noncomputable section', '', 'namespace LSG.JacBlock', '', 'open LSG.JacAn LSG.Jac Finset', '']
    L += [f'theorem tanC{cname}_cont (j : Fin 2) (i k : Fin 12) : Continuous (tanC{cname} j i k) := by',
          '  fin_cases j <;> fin_cases i',
          ] + [f'  · exact tanC{cname}_cont_{j}_{i} k' for j in range(2) for i in range(12)] + ['',
          f'/-- **Tangency of the chart-{cname} flow** (ideal form, all `X`). -/',
          f'theorem gens_tan{cname} (j : Fin 2) (i : Fin 12) (X : P9) :',
          f'    fderiv ℂ (gensA i) X (W{cname}G j X) = ∑ k, tanC{cname} j i k X * gensA k X := by',
          '  fin_cases j <;> fin_cases i',
          ] + [f'  · exact gens_tan{cname}_{j}_{i} X' for j in range(2) for i in range(12)] + ['',
          'end LSG.JacBlock', '']
    path = os.path.join(ROOT, 'LSG', 'JacBlock', f'Tan{cname}.lean')
    open(path, 'w', encoding='utf-8').write('\n'.join(L))
    print('wrote', path)
