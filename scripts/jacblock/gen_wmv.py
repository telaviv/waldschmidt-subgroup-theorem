"""Generate LSG/JacBlock/WMv.lean: the chart fields (flowW, W4C, W8C; speed 1) as MvPolynomials (UNTRUSTED;
Lean checks eval = the A1 maps by `ring`).  Usage: python gen_wmv.py"""
from jb_common import *


def lmon(p):
    if p == 0:
        return '0'
    ts = []
    for e, c in sorted(p.to_dict().items(), reverse=True):
        c = Fraction(int(c.p), int(c.q))
        cs = f'({c.numerator} / {c.denominator})' if c.denominator != 1 else f'({c.numerator})'
        l = [i for i in range(9) for _ in range(e[i])]
        ts.append(f'mon {cs} {l}')
    return ' + '.join(ts)


L = ['/-', 'Copyright (c) 2026. All rights reserved.', 'Released under Apache 2.0 license.', '-/',
     'import LSG.JacBlock.GensMv', '',
     '/-! GENERATED by scripts/jacblock/gen_wmv.py — do not edit.', '',
     '# The chart fields of the A-block as `MvPolynomial`s (`W` field, speed 1)', '',
     '`Wmv 0 = flowW`, `Wmv 4 = W4G` (A1\'s `W4C = W4n/4`), `Wmv 8 = W8G` (`W8C`), and `0` in the other charts.',
     '-/', '', 'noncomputable section', '', 'namespace LSG.JacBlock', '', 'open MvPolynomial LSG.JacAn', '']
for nm, F in (('Wc0', W), ('Wc4', W4), ('Wc8', W8)):
    L.append(f'def {nm} : Fin 2 → Fin 9 → MvPolynomial (Fin 9) ℂ := ![')
    L.append(',\n'.join('  ![' + ', '.join(lmon(F[j][l]) for l in range(9)) + ']' for j in range(2)) + ']')
    L.append('')
L += ['/-- The chart fields. -/',
      'def Wmv (c : Fin 9) (j : Fin 2) (l : Fin 9) : MvPolynomial (Fin 9) ℂ :=',
      '  if c = 0 then Wc0 j l else if c = 4 then Wc4 j l else if c = 8 then Wc8 j l else 0', '']
for nm, tgt, unf in (('Wc0', 'flowW j X l', 'flowW'), ('Wc4', 'W4G j X l', 'W4G, LSG.Jac.W4n'),
                     ('Wc8', 'W8G j X l', 'W8G, LSG.Jac.W8n')):
    L += [f'lemma eval_{nm} (j : Fin 2) (l : Fin 9) (X : Fin 9 → ℂ) : eval X ({nm} j l) = {tgt} := by',
          f'  fin_cases j <;> fin_cases l <;> simp [{nm}, {unf}] <;> ring', '']
    L += [f'lemma {nm}_hom (j : Fin 2) (l : Fin 9) : ({nm} j l).IsHomogeneous 2 := by',
          f'  fin_cases j <;> fin_cases l <;> simp only [{nm}, Matrix.cons_val, Fin.isValue, Fin.zero_eta,',
          '    Fin.mk_one, Fin.reduceFinMk] <;>',
          '    first | exact isHomogeneous_zero _ _ _ | apply_rules [IsHomogeneous.add, isHomogeneous_mon]', '']
L += ['lemma Wmv_hom (c : Fin 9) (j : Fin 2) (l : Fin 9) : (Wmv c j l).IsHomogeneous 2 := by',
      '  unfold Wmv',
      '  split_ifs',
      '  · exact Wc0_hom j l',
      '  · exact Wc4_hom j l',
      '  · exact Wc8_hom j l',
      '  · exact isHomogeneous_zero _ _ _', '',
      'lemma Wmv_chart (c : Fin 9) (j : Fin 2) : Wmv c j c = 0 := by',
      '  fin_cases c <;> fin_cases j <;> simp [Wmv, Wc0, Wc4, Wc8]', '',
      'end LSG.JacBlock', '']
open(os.path.join(ROOT, 'LSG', 'JacBlock', 'WMv.lean'), 'w', encoding='utf-8').write('\n'.join(L))
print('wrote WMv.lean')
